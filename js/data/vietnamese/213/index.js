    const than = document.getElementById('ipt-213-than').value.trim();
    const ket = document.getElementById('ipt-213-ket').value.trim();
    const fb = document.getElementById('fb-213-outline');
    
    fb.classList.remove('opacity-0');
    
    if (!landscape || !mo || !than || !ket) {
        fb.className = "text-xl font-black text-red-600 opacity-100 flex items-center gap-2";
        fb.innerHTML = "❌ Em vui lòng điền đầy đủ các phần của dàn ý nhé!";
        if (window.UI && typeof window.UI.showToast === 'function') {
            window.UI.showToast("Hãy điền hoàn chỉnh thông tin dàn ý!", "error");
        }
        return;
    }
    
    // Kiểm tra Checklist
    const chk1 = document.getElementById('chk-213-1').checked;
    const chk2 = document.getElementById('chk-213-2').checked;
    const chk3 = document.getElementById('chk-213-3').checked;
    
    if (!chk1 || !chk2 || !chk3) {
        fb.className = "text-xl font-black text-amber-600 opacity-100 flex items-center gap-2";
        fb.innerHTML = "⚠️ Em hãy tích đủ vào Phiếu tự đánh giá và chỉnh sửa ở dưới nhé!";
        return;
    }

    fb.className = "text-xl font-black text-green-600 opacity-100 flex items-center gap-2";
    fb.innerHTML = `🎉 Tuyệt vời! Dàn ý tả <b>${landscape}</b> của em đã được nộp và ghi nhận thành công!`;
    
