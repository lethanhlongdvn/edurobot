// Các hàm kiểm tra bài tập lập dàn ý
window.checkDanY220 = function() {
    const name = document.getElementById('ipt-220-name').value.trim();
    const mobai = document.getElementById('ipt-220-mobai').value.trim();
    const ngoaihinh = document.getElementById('ipt-220-ngoaihinh').value.trim();
    const hoatdong = document.getElementById('ipt-220-hoatdong').value.trim();
    const ketbai = document.getElementById('ipt-220-ketbai').value.trim();
    const fb = document.getElementById('fb-dany-220');
    fb.classList.remove('hidden');

    if (!name || !mobai || !ngoaihinh || !hoatdong || !ketbai) {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-orange-100 text-orange-800 border border-orange-200 mt-4 animate-in fade-in";
        fb.innerHTML = "⚠️ Em vui lòng điền đầy đủ tất cả các phần trong dàn ý để hoàn thành bài tập nhé!";
        if (window.UI && typeof window.UI.showToast === 'function') {
            window.UI.showToast("Hãy hoàn thiện các mục trong dàn ý!", "error");
        }
        return;
    }

    fb.className = "p-4 rounded-xl font-bold text-lg bg-green-100 text-green-800 border border-green-200 mt-4 animate-in fade-in";
    fb.innerHTML = `🌟 Tuyệt vời! Em đã lập xong dàn ý tả thầy/cô giáo <b>${name}</b> với đầy đủ 3 phần (Mở bài - Thân bài - Kết bài). Hãy tự tin chuẩn bị viết bài văn hoàn chỉnh nhé!`;
    
    if (window.UI && typeof window.UI.showToast === 'function') {
        window.UI.showToast("Lập dàn ý thành công!", "success");
    }
    if (typeof window.playAudioHelper === 'function') { window.playAudioHelper('correct'); }
    
    // Gọi submit lưu điểm
    if (typeof window.submitMathLesson === 'function') {
        window.submitMathLesson("Viết Tiết 220: Tự lập dàn ý", 100, "ex-220-dany", 1, 1, 1);
    }
};

