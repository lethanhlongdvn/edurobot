let nvnHistoryList = [];

window.nvn222_send = function() {
    const input = document.getElementById("btn-nvn-input");
    if (!input) return;
    const text = input.value.trim();
    if (!text) {
        if (typeof window.UI !== 'undefined' && window.UI.showToast) {
            window.UI.showToast("Cậu chưa nhập ý kiến tranh biện kìa! ✏️", "error", 3000);
        } else {
            alert("Cậu chưa nhập ý kiến tranh biện kìa! ✏️");
        }
        return;
    }

    const historyBox = document.getElementById("nvn-chat-history");
    if (!historyBox) return;

    // Hiển thị tin nhắn của Học sinh
    const userBubble = document.createElement("div");
    userBubble.className = "self-end max-w-[85%] animate-in slide-in-from-right duration-300";
    userBubble.innerHTML = `
        <div class="flex items-center gap-2 mb-2 justify-end">
            <span class="text-sm font-black text-blue-600 uppercase bg-blue-100 px-2 py-0.5 rounded-lg">Học sinh</span>
        </div>
        <div class="bg-blue-600 p-5 rounded-3xl rounded-tr-none border border-blue-500 text-white text-xl md:text-2xl font-bold leading-relaxed shadow-md">
            \${text}
        </div>
    `;
    historyBox.appendChild(userBubble);
    nvnHistoryList.push({ role: "user", text: text });
    
    input.value = "";
    historyBox.scrollTop = historyBox.scrollHeight;

    // AI Minh Trí phân tích phản hồi
    setTimeout(() => {
        const textLower = text.toLowerCase();
        let reply = "";

        const isSupport = textLower.includes("ủng hộ") || textLower.includes("tán thành") || textLower.includes("nên") || textLower.includes("đồng ý") || textLower.includes("đồng tình") || textLower.includes("đúng") || textLower.includes("tự lập") || textLower.includes("quản lý") || textLower.includes("mua đồ") || textLower.includes("giá trị");
        const isOppose = textLower.includes("phản đối") || textLower.includes("không nên") || textLower.includes("không đồng ý") || textLower.includes("chưa đúng") || textLower.includes("hoang phí") || textLower.includes("đua đòi") || textLower.includes("bắt chước") || textLower.includes("phung phí") || textLower.includes("không cần thiết");

        if (isSupport && !isOppose) {
            reply = "Tớ hiểu góc nhìn của cậu! Đồng ý là giữ tiền riêng giúp chúng mình tự lập, học cách quản lý tài chính và biết quý trọng công sức bố mẹ hơn. Nhưng cậu có lo rằng ở tuổi này chúng mình chưa đủ chín chắn, dễ sa đà mua đồ ăn vặt linh tinh hoặc đua đòi theo bạn bè gây lãng phí không? Cậu giải thích sao về điểm này? 🤔";
        } else if (isOppose && !isSupport) {
            reply = "Ý kiến phản đối của cậu rất thực tế và đáng suy ngẫm! Đúng là nếu tự giữ tiền, chúng mình có thể ham vui mà tiêu xài hoang phí hoặc đua đòi. Nhưng nếu bố mẹ quản lý hết 100% và không bao giờ cho chúng mình tự giữ tiền, thì làm sao chúng mình học được cách quản lý chi tiêu và biết quý giá trị của đồng tiền qua trải nghiệm thực tế được nhỉ? Cậu nghĩ sao? 💡";
        } else {
            reply = "Ồ, lập luận của cậu khá thú vị! Để tranh biện sắc bén hơn, cậu có thể nêu rõ bản thân <b>tán thành</b> hay <b>phản đối</b> việc học sinh giữ tiền riêng để tiêu, và đưa ra một lí lẽ cụ thể kèm ví dụ được không? 😉";
        }

        const botBubble = document.createElement("div");
        botBubble.className = "self-start max-w-[85%] animate-in slide-in-from-left duration-300";
        botBubble.innerHTML = `
            <div class="flex items-center gap-2 mb-2">
                <div class="inline-flex w-7 h-7 bg-blue-600 rounded-lg items-center justify-center text-white font-black text-xs shadow-sm">E</div>
                <span class="text-sm font-black text-amber-600 uppercase bg-amber-100 px-2 py-0.5 rounded-lg">Minh Trí_EduRobot</span>
            </div>
            <div class="bg-white p-5 rounded-3xl rounded-tl-none border border-gray-100 shadow-md text-xl md:text-2xl font-bold text-gray-800 leading-relaxed">
                \${reply}
            </div>
        `;
        historyBox.appendChild(botBubble);
        nvnHistoryList.push({ role: "bot", text: reply });
        historyBox.scrollTop = historyBox.scrollHeight;
    }, 1000);
};

