// Kiểm tra bài tập nối cấu trúc
window.checkLt227 = function() {
    const modau = document.getElementById('sel-227-modau').value; // Mở đầu -> gioithieu
    const trienkhai = document.getElementById('sel-227-trienkhai').value; // Triển khai -> lydo
    const kethuc = document.getElementById('sel-227-kethuc').value; // Kết thúc -> ynghia
    const fb = document.getElementById('fb-lt-227');
    fb.classList.remove('hidden');

    if (!modau || !trienkhai || !kethuc) {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-orange-100 text-orange-800 border border-orange-200 mt-4";
        fb.innerHTML = "⚠️ Em vui lòng chọn nội dung tương ứng cho cả 3 phần nhé!";
        return;
    }

    if (modau === 'gioithieu' && trienkhai === 'lydo' && kethuc === 'ynghia') {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-green-100 text-green-800 border border-green-200 mt-4";
        fb.innerHTML = "🌟 Tuyệt vời! Em đã ghép nối hoàn toàn chính xác chức năng của 3 phần cấu trúc của đoạn văn nêu ý kiến phản đối.";
        if (typeof window.playAudioHelper === 'function') { window.playAudioHelper('correct'); }
        
        // Lưu điểm
        if (typeof window.submitMathLesson === 'function') {
            window.submitMathLesson("Viết Tiết 227: Ghép nối cấu trúc phản đối", 100, "ex-227-match", 1, 1, 1);
        }
    } else {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-red-100 text-red-800 border border-red-200 mt-4";
        fb.innerHTML = "❌ Chưa chính xác rồi. Em hãy đọc kỹ phần 'Ghi nhớ' ở ngay phía trên để nối lại cho đúng nhé!";
        if (typeof window.playAudioHelper === 'function') { window.playAudioHelper('incorrect'); }
    }
};

window.resetLt227 = function() {
    document.getElementById('sel-227-modau').value = "";
    document.getElementById('sel-227-trienkhai').value = "";
    document.getElementById('sel-227-kethuc').value = "";
    const fb = document.getElementById('fb-lt-227');
    fb.classList.add('hidden');
    fb.innerHTML = "";
};