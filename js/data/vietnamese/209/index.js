window.submitWriting_209 = function() {
    const text = document.getElementById('ans-209-writing').value.trim();
    const fb = document.getElementById('fb-209-writing');
    
    if (!text) {
        fb.className = "text-xl font-black text-red-600 opacity-100 flex items-center gap-2";
        fb.innerHTML = "❌ Em chưa nhập bài làm mà!";
        if (window.UI && typeof window.UI.showToast === 'function') {
            window.UI.showToast("Hãy nhập bài viết trước khi nộp nhé!", "error");
        }
        return;
    }
    
    if (text.length < 50) {
        fb.className = "text-xl font-black text-amber-600 opacity-100 flex items-center gap-2";
        fb.innerHTML = "⚠️ Đoạn văn hơi ngắn rồi, em hãy viết dài thêm một chút nữa nhé!";
        return;
    }
    
    // Kiểm tra Checklist
    const chk1 = document.getElementById('chk-209-1').checked;
    const chk2 = document.getElementById('chk-209-2').checked;
    const chk3 = document.getElementById('chk-209-3').checked;
    
    if (!chk1 || !chk2 || !chk3) {
        fb.className = "text-xl font-black text-amber-600 opacity-100 flex items-center gap-2";
        fb.innerHTML = "⚠️ Em hãy đọc và tích đủ vào Phiếu tự nhận xét bên dưới nhé!";
        return;
    }

    fb.className = "text-xl font-black text-green-600 opacity-100 flex items-center gap-2";
    fb.innerHTML = "🎉 Tuyệt vời! Em đã hoàn thành xuất sắc bài luyện viết. Bài làm đã được ghi nhận!";
    
    if (window.UI && typeof window.UI.showToast === 'function') {
        window.UI.showToast("Nộp bài luyện viết thành công!", "success");
    }
    if (typeof window.playAudioHelper === 'function') { window.playAudioHelper('correct'); }
    
    // Gọi hàm chuẩn lưu bài nếu có
    if (typeof window.submitMathLesson === 'function') {
        window.submitMathLesson("Viết Tiết 209: Luyện viết đoạn văn", 100, "ex-209-practice-section", 1, 1, 1);
    }
};
