window.checkLTVC170_3 = function() {
    const a = document.getElementById("ltvc170-3a").value.trim().toLowerCase();
    const b = document.getElementById("ltvc170-3b").value.trim().toLowerCase();
    const c = document.getElementById("ltvc170-3c").value.trim().toLowerCase();

    const fb = document.getElementById("ltvc170-3-feedback");
    if (!fb) return;

    fb.classList.remove("hidden", "bg-green-50", "text-green-800", "bg-red-50", "text-red-800");

    // Từ khóa chấp nhận:
    // a: "những nghệ nhân người mông" hoặc "nghệ nhân người mông"
    // b: "con dơi" hoặc "dơi"
    // c: "con chim họa mi" hoặc "chim họa mi" hoặc "chim hoa mi"
    const isAOk = a.includes("nghệ nhân") && a.includes("mông");
    const isBOk = b.includes("con dơi") || b === "dơi";
    const isCOk = c.includes("họa mi") || c.includes("hoa mi");

    if (isAOk && isBOk && isCOk) {
        fb.classList.add("bg-green-50", "text-green-800");
        fb.innerHTML = "🎉 Tuyệt vời! Em đã trả lời chính xác tất cả các từ được thay thế trong cả 3 câu. Hãy tiếp tục làm bài tập 4 nhé!";
    } else {
        fb.classList.add("bg-red-50", "text-red-800");
        fb.innerHTML = "❌ Câu trả lời chưa hoàn toàn chính xác. Gợi ý: a) nghệ nhân người Mông, b) con dơi, c) con chim họa mi. Em hãy kiểm tra và thử lại nhé!";
    }
};

