// Accordion helper
window.toggleAcc218 = function(id) {
    const acc = document.getElementById(id);
    const icon = document.getElementById('icon-' + id);
    if (acc.classList.contains('hidden')) {
        acc.classList.remove('hidden');
        icon.innerText = '−';
    } else {
        acc.classList.add('hidden');
        icon.innerText = '+';
    }
};

