window.handleTamDrop = function(event, groupId) {
    event.preventDefault();
    if (!dragWordDataVn116) return;

    // Check if word already dragged to a group
    const wordId = dragWordDataVn116.id;
    
    // Remove from other group if existing
    const otherGroupId = groupId === 'group-center' ? 'group-mind' : 'group-center';
    userSortingVn116[otherGroupId] = userSortingVn116[otherGroupId].filter(id => id !== wordId);
    
    // Add to current group
    if (!userSortingVn116[groupId].includes(wordId)) {
        userSortingVn116[groupId].push(wordId);
    }

    // Hide placeholder text if not empty
    const zone = document.getElementById(groupId);
    if (zone) {
        zone.innerHTML = "";
        userSortingVn116[groupId].forEach(id => {
            const cardText = document.getElementById(id)?.innerText || "";
            const wordEl = document.createElement('div');
            wordEl.className = "px-4 py-2 bg-yellow-400 text-gray-900 border border-yellow-500 rounded-xl font-bold text-sm shadow-sm cursor-pointer";
            wordEl.innerText = cardText;
            zone.appendChild(wordEl);
        });
    }

    // Disable in source container
    const originalEl = document.getElementById(wordId);
    if (originalEl) originalEl.className += " opacity-30 cursor-not-allowed";
};

