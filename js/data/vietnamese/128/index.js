window.toggleSpeechRecVn128 = function() {
    const txt = document.getElementById('ans-vn128-writing');
    if (!txt) return;
    if (!('webkitSpeechRecognition' in window) && !('SpeechRecognition' in window)) {
        alert("Trình duyệt không hỗ trợ nhận diện giọng nói.");
        return;
    }
    const SpeechRec = window.SpeechRecognition || window.webkitSpeechRecognition;
    const rec = new SpeechRec();
    rec.lang = 'vi-VN';
    rec.onstart = () => {
        txt.placeholder = "🎙️ Đang lắng nghe con nói...";
    };
    rec.onresult = (event) => {
        const result = event.results[0][0].transcript;
        txt.value = txt.value ? txt.value + " " + result : result;
        txt.placeholder = "Viết câu ghép về Nai Ngọc...";
    };
    rec.onerror = () => {
        txt.placeholder = "Viết câu ghép về Nai Ngọc...";
    };
    rec.start();
};

