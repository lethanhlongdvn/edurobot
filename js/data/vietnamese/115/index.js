// 4. Nhập giọng nói Speech-to-Text
window.startVoiceInputVn115 = function(fieldId) {
    const txt = document.getElementById(fieldId);
    if (!txt) return;
    if (!('webkitSpeechRecognition' in window) && !('SpeechRecognition' in window)) {
        alert("Trình duyệt không hỗ trợ nhận diện giọng nói.");
        return;
    }
    const SpeechRec = window.SpeechRecognition || window.webkitSpeechRecognition;
    const rec = new SpeechRec();
    rec.lang = 'vi-VN';
    rec.onstart = () => {
        txt.placeholder = "🎙️ Đang nghe con nói...";
    };
    rec.onresult = (event) => {
        const result = event.results[0][0].transcript;
        txt.value = txt.value ? txt.value + " " + result : result;
        txt.placeholder = "Nhập đoạn văn của con...";
        window.updateWordCountVn115();
    };
    rec.onerror = () => {
        txt.placeholder = "Nhập đoạn văn của con...";
    };
    rec.start();
};

