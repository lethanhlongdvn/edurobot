// Nhập bằng giọng nói cho bài tập 2
window.batGiongNoi158 = function () {
    if (window.UI && typeof window.UI.showToast === 'function') {
        window.UI.showToast("Tính năng nhập bằng giọng nói đang khởi động...", "success");
    }
    const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
    if (!SpeechRecognition) {
        alert("Trình duyệt không hỗ trợ nhận dạng giọng nói.");
        return;
    }
    const rec = new SpeechRecognition();
    rec.lang = 'vi-VN';
    rec.start();
    rec.onresult = function (event) {
        const txt = event.results[0][0].transcript;
        const textarea = document.getElementById('ai-158-lt2');
        if (textarea) textarea.value = (textarea.value + " " + txt).trim();
    };
};

