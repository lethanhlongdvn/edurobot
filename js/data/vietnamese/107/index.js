// 1. Logic click chọn từ nối (Câu 2)
let selectedWordsVn107 = {
    a: new Set(),
    b: new Set(),
    c: new Set(),
    d: new Set()
};

window.toggleWordSelect = function(element, sentenceId) {
    const word = element.getAttribute('data-word');
    if (selectedWordsVn107[sentenceId].has(word)) {
        selectedWordsVn107[sentenceId].delete(word);
        element.className = "cursor-pointer hover:bg-yellow-200 px-1 rounded transition-colors text-slate-800";
    } else {
        selectedWordsVn107[sentenceId].add(word);
        element.className = "cursor-pointer bg-lime-500 text-white px-1 rounded transition-colors shadow-sm font-black";
    }
};

window.checkClickWordsVn107 = function() {
    const feedback = document.getElementById('click-words-feedback');
    if (!feedback) return;
    feedback.classList.remove('hidden');

    const ansA = selectedWordsVn107.a.has('Vì') && selectedWordsVn107.a.has('nên') && selectedWordsVn107.a.size === 2;
    const ansB = selectedWordsVn107.b.has('Mặc dù') && selectedWordsVn107.b.has('nhưng') && selectedWordsVn107.b.size === 2;
    const ansC = selectedWordsVn107.c.has('không những') && selectedWordsVn107.c.has('mà còn') && selectedWordsVn107.c.size === 2;
    const ansD = selectedWordsVn107.d.has('Nếu') && selectedWordsVn107.d.has('thì') && selectedWordsVn107.d.size === 2;

    if (ansA && ansB && ansC && ansD) {
        feedback.innerHTML = "🎉 Tuyệt vời! Em đã chỉ ra chính xác tất cả các cặp kết từ dùng trong câu rồi đó!";
        feedback.className = "mt-4 p-4 rounded-xl font-bold text-lg bg-emerald-600 text-white text-center shadow-lg animate-fade-in";
        if (typeof window.UI?.showToast === 'function') {
            window.UI.showToast("Cặp kết từ hoàn toàn chính xác!", "success", 3000);
        }
    } else {
        feedback.innerHTML = "❌ Còn một vài câu em chọn chưa đúng hoặc chưa đủ cặp kết từ. Hãy kiểm tra lại nhé!";
        feedback.className = "mt-4 p-4 rounded-xl font-bold text-lg bg-red-500 text-white text-center shadow-lg animate-fade-in";
        if (typeof window.UI?.showToast === 'function') {
            window.UI.showToast("Lựa chọn chưa chính xác!", "error", 4000);
        }
    }
};

