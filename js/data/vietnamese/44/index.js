let chanDone = false;
window.kiemTraChan = function(btn, isCorrect) {
    if (chanDone) return;
    const fb = document.getElementById('fb-vn44-chan');
    if (!fb) return;
    fb.classList.remove('hidden');
    if (isCorrect) {
        btn.className = 'w-full p-4 bg-emerald-600 text-white border-2 border-emerald-100 rounded-2xl text-left font-black cursor-default';
        fb.innerHTML = '🎉 Đúng! Câu C dùng "chân" với nghĩa gốc – bộ phận thân thể dùng để đi lại của con người.';
        fb.className = 'p-4 rounded-xl text-center text-lg font-black bg-emerald-50 text-emerald-800 border border-emerald-100 transition-all';
        chanDone = true;
        if (typeof window.showMathFeedback === 'function') {
            window.showMathFeedback('Chính xác!', '🦶', 'Em đã nhận biết đúng nghĩa gốc của từ "chân"!');
        }
    } else {
        btn.className = 'w-full p-4 bg-rose-600 text-white border-2 border-rose-100 rounded-2xl text-left font-black scale-95';
        fb.innerHTML = '❌ Chưa đúng! "Chân bàn", "chân núi", "chân cột" đều là nghĩa chuyển. Nghĩa gốc của "chân" là bộ phận cơ thể người/động vật dùng để đi lại.';
        fb.className = 'p-4 rounded-xl text-center text-lg font-black bg-rose-50 text-rose-800 border border-rose-100 transition-all';
        setTimeout(() => {
            btn.className = 'w-full p-4 bg-white hover:bg-teal-50 border-2 border-gray-100 rounded-2xl text-left transition-all active:scale-95 font-bold text-xl md:text-2xl';
            fb.classList.add('hidden');
        }, 3044);
    }
};

