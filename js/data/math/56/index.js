// Helper Functions
function normalize(str) {
    if (!str) return '';
    return str.toString().replace(/\s+/g, ' ').trim().toLowerCase();
}

function normalizeCompare(val, standard) {
    return normalize(val) === normalize(standard);
}

function compareSegment(val, standard) {
    var v = normalize(val);
    var s = normalize(standard);
    if (v.length === 2 && s.length === 2) {
        return (v.split('').sort().join('') === s.split('').sort().join(''));
    }
    return v === s;
}

