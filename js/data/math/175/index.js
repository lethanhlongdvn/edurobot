window.check_175_1 = function() {
    const checks = [
        {id:'175-1-1', ans:['VẬT','VAT']},
        {id:'175-1-2', ans:['12']},
        {id:'175-1-p1', ans:['50%','50']},
        {id:'175-1-p2', ans:['15%','15']},
        {id:'175-1-p3', ans:['35%','35']},
    ];
    let correct = 0;
    checks.forEach(c => {
        const el = document.getElementById(c.id);
        if (!el) return;
        const v = el.value.trim().toUpperCase().replace(/\s/g,'');
        if (c.ans.includes(v)) { el.classList.add('bg-green-100','border-green-500'); el.classList.remove('bg-red-100','border-red-500'); correct++; }
        else { el.classList.add('bg-red-100','border-red-500'); el.classList.remove('bg-green-100','border-green-500'); }
    });

    const eq1 = document.getElementById('175-1-eq1');
    const eq2 = document.getElementById('175-1-eq2');
    if (eq1 && eq2) {
        const v1 = eq1.value.trim().toUpperCase().replace(/\s/g,'');
        const v2 = eq2.value.trim().toUpperCase().replace(/\s/g,'');
        const validPairs = [
            ['WUSHU', 'LẶN'], ['WUSHU', 'LAN'],
            ['LẶN', 'WUSHU'], ['LAN', 'WUSHU']
        ];
        const isEqCorrect = validPairs.some(pair => (v1 === pair[0] && v2 === pair[1]));
        if (isEqCorrect) {
            eq1.classList.add('bg-green-100','border-green-500'); eq1.classList.remove('bg-red-100','border-red-500');
            eq2.classList.add('bg-green-100','border-green-500'); eq2.classList.remove('bg-red-100','border-red-500');
            correct += 2;
        } else {
            eq1.classList.add('bg-red-100','border-red-500'); eq1.classList.remove('bg-green-100','border-green-500');
            eq2.classList.add('bg-red-100','border-red-500'); eq2.classList.remove('bg-green-100','border-green-500');
        }
    }

    const totalQuestions = checks.length + 2;
    const isCorrect = correct === totalQuestions;
    window.showMathFeedback(isCorrect,
        "a) Môn nhiều HCV nhất: Vật (17 HCV); Hai môn bằng nhau: Wushu và Lặn; TB: 12 HCV<br>b) HCV: 50%, HCB: 15%, HCĐ: 35%",
        "",
        "Gợi ý:<br>a) Đọc đỉnh cột cao nhất để tìm môn nhiều HCV nhất (Vật). Hai môn có số HCV bằng nhau là Wushu và Lặn (cùng 10 HCV). Trung bình = (17+11+10+10):4 = 12.<br>b) Tổng HC Wushu = 20 → HCV: 10/20=50%, HCB: 3/20=15%, HCĐ: 7/20=35%.",
        "a) Vật (17 HCV); Wushu và Lặn (10 HCV); TB: 12 HCV.<br>b) HCV 50%, HCB 15%, HCĐ 35%.<br>Chúc mừng em!"
    );
    if (window.submitMathLesson) window.submitMathLesson("Bài 1. Thống kê Sea Games 31", Math.round(correct/totalQuestions*100), "btn-check-175-1", 0, totalQuestions, correct);
};

