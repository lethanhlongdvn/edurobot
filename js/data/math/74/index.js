window.drawPencilLine74 = function(penVal, potVal) {
    const penId = 'pen-' + penVal.replace(',', '_');
    const potId = 'pot-' + potVal.replace(',', '_');
    
    const container = document.getElementById('match-container-74');
    const svg = document.getElementById('svg-lines-74');
    const penEl = document.getElementById(penId);
    const potEl = document.getElementById(potId);
    if (!container || !svg || !penEl || !potEl) return;

    const containerRect = container.getBoundingClientRect();
    const penRect = penEl.getBoundingClientRect();
    const potRect = potEl.getBoundingClientRect();

    const x1 = penRect.left + penRect.width / 2 - containerRect.left;
    const y1 = penRect.top + penRect.height / 2 - containerRect.top;
    const x2 = potRect.left + potRect.width / 2 - containerRect.left;
    const y2 = potRect.top + potRect.height / 2 - containerRect.top;

    const line = document.createElementNS('http://www.w3.org/2000/svg', 'line');
    line.setAttribute('x1', x1);
    line.setAttribute('y1', y1);
    line.setAttribute('x2', x2);
    line.setAttribute('y2', y2);
    line.setAttribute('stroke', '#1d4ed8');
    line.setAttribute('stroke-width', '4');
    line.setAttribute('stroke-dasharray', '8,4');
    line.setAttribute('stroke-linecap', 'round');
    line.style.filter = 'drop-shadow(1px 1px 1px rgba(0,0,0,0.15))';
    svg.appendChild(line);
};

