window.check_89_bt1 = function() {
    const answers = metadata.bai_tap[0].answers;
    const ids = [
        'inp-89-bt1-1', 'inp-89-bt1-2', 'inp-89-bt1-3', 'inp-89-bt1-4',
        'inp-89-bt1-5', 'inp-89-bt1-6', 'inp-89-bt1-7', 'inp-89-bt1-8'
    ];
    let correctCount = 0;
    const totalQuestions = ids.length;

    for (let i = 0; i < totalQuestions; i++) {
        let val = document.getElementById(ids[i]).value.trim().replace(/\s+/g, ' ').toLowerCase();
        if (i < 4) {
            // Viết số thập phân
            let cleanVal = val.replace(',', '.');
            let cleanAns = answers[i].replace(',', '.');
            if (cleanVal === cleanAns) {
                correctCount++;
            }
        } else {
            // Đọc số thập phân bằng chữ
            // Thay thế lẻ/linh/tư/bốn để hỗ trợ nhiều cách viết của học sinh
            let processedVal = val.replace(/lẻ/g, 'linh').replace(/bốn/g, 'tư').replace(/ /g, '');
            let processedAns = answers[i].replace(/lẻ/g, 'linh').replace(/bốn/g, 'tư').replace(/ /g, '');
            if (processedVal === processedAns) {
                correctCount++;
            }
        }
    }

    const isCorrect = (correctCount === totalQuestions);

    const rightAnswer = "a) 123.457, 67.52, 803.455, 19.05; b) đọc số bằng tiếng Việt đúng";
    const studentAnswer = `Điền đúng ${correctCount}/${totalQuestions} ô.`;
    const guidance = metadata.bai_tap[0].guidance;
    const solution = metadata.bai_tap[0].solution;

    window.showMathFeedback(isCorrect, rightAnswer, studentAnswer, guidance, solution);

    if (window.submitMathLesson) {
        window.submitMathLesson("Bài 1: Đọc và viết số thập phân", isCorrect ? 100 : 0, 'btn-check-89-bt1', 0, totalQuestions, correctCount);
    }
};

