window.selectOption89 = function(btn) {
    const val = btn.dataset.value;
    const container = document.getElementById('dd-ex-89-bt2');
    if (!container) return;
    const slots = container.querySelectorAll('.dd-slot');
    let targetSlot = null;
    for (let slot of slots) {
        if (!slot.dataset.value) {
            targetSlot = slot;
            break;
        }
    }
    if (targetSlot) {
        targetSlot.innerText = val;
        targetSlot.dataset.value = val;
        targetSlot.classList.remove('border-dashed', 'bg-blue-50/50');
        targetSlot.classList.add('bg-blue-600', 'text-white', 'border-solid');
        btn.classList.add('opacity-30', 'pointer-events-none');
    }
};

window.clickSlot89 = function(slot) {
    const val = slot.dataset.value;
    if (!val) return;
    slot.innerText = '';
    delete slot.dataset.value;
    slot.classList.add('border-dashed', 'bg-blue-50/50');
    slot.classList.remove('bg-blue-600', 'text-white', 'border-solid');
    const container = document.getElementById('dd-ex-89-bt2');
    if (container) {
        const option = Array.from(container.querySelectorAll('.dd-option')).find(btn => btn.dataset.value === val);
        if (option) {
            option.classList.remove('opacity-30', 'pointer-events-none');
        }
    }
};

window.clearOption89 = function() {
    window.Lesson.clearSlots('89-bt2');
    const container = document.getElementById('dd-ex-89-bt2');
    if (!container) return;
    container.querySelectorAll('.dd-option').forEach(btn => {
        btn.classList.remove('opacity-30', 'pointer-events-none');
    });
};

