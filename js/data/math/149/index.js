window.rolls_149 = { even: 0, odd: 0, total: 0, choice: "" };

window.setChoice149 = function (c) {
    window.rolls_149.choice = c;
    const sBtn = document.getElementById("choice-story");
    const cBtn = document.getElementById("choice-cake");
    if (!sBtn || !cBtn) return;
    sBtn.className = "px-8 py-4 rounded-2xl border-2 font-bold text-2xl " + (c === "story" ? "bg-blue-600 text-white border-blue-600" : "border-blue-200 text-slate-400 shadow-sm");
    cBtn.className = "px-8 py-4 rounded-2xl border-2 font-bold text-2xl " + (c === "cake" ? "bg-blue-600 text-white border-blue-600" : "border-blue-200 text-slate-400 shadow-sm");
};

window.rollDice149 = function () {
    if (window.rolls_149.total >= 9) return;
    const cube = document.getElementById("dice-cube-149");
    const btn = document.getElementById("btn-roll");
    if (!cube || !btn) return;
    btn.disabled = true;
    const val = Math.floor(Math.random() * 6) + 1;
    const rots = { 1: { x: 0, y: 0 }, 2: { x: -90, y: 0 }, 3: { x: 0, y: -90 }, 4: { x: 0, y: 90 }, 5: { x: 90, y: 0 }, 6: { x: 180, y: 0 } };
    const r = rots[val];
    const baseRot = (window.rolls_149.total + 1) * 360 * 4; // 4 full continuous rounds
    cube.style.transform = `rotateX(${r.x + baseRot}deg) rotateY(${r.y + baseRot}deg)`;
    setTimeout(() => {
        window.rolls_149.total++;
        if (val % 2 === 0) window.rolls_149.even++; else window.rolls_149.odd++;
        document.getElementById("roll-count").innerText = window.rolls_149.total;
        document.getElementById("res-even").innerText = window.rolls_149.even;
        document.getElementById("res-odd").innerText = window.rolls_149.odd;
        btn.disabled = false;
        if (window.rolls_149.total === 9) btn.innerText = "XONG!";
    }, 1800);
};

window.check_149_1 = function () {
    const userAns = [
        document.getElementById("in-149-1-1")?.value,
        document.getElementById("in-149-1-2")?.value,
        document.getElementById("in-149-1-3")?.value,
        document.getElementById("in-149-1-4")?.value
    ];
    const meta = metadata.exercises[0];
    const answers = meta.answers;
    let correctCount = 0;
    userAns.forEach((val, i) => {
        if (val === answers[i]) correctCount++;
    });

    const isCorrect = correctCount === answers.length;
    window.showMathFeedback(isCorrect, answers.join(", "), "", meta.guidance, meta.solution);
    if (window.submitMathLesson) {
        window.submitMathLesson("Bài 1. Tỉ số lấy tất", isCorrect ? 100 : Math.round((correctCount / answers.length) * 100), "btn-check-149-1", 0, answers.length, correctCount);
    }
};

