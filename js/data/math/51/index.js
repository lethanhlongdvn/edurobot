window.check_51_1 = function() {
    var a1 = document.getElementById('ans-51-1-a1').value.trim();
    var a2 = document.getElementById('ans-51-1-a2').value.trim();
    var a3 = document.getElementById('ans-51-1-a3').value.trim();
    var b1 = document.getElementById('ans-51-1-b1').value.trim();
    var b2 = document.getElementById('ans-51-1-b2').value.trim();
    var b3 = document.getElementById('ans-51-1-b3').value.trim();

    var isCorrect = (
        normalizeCompare(a1, '96.3') &&
        normalizeCompare(a2, '94') &&
        normalizeCompare(a3, '2080') &&
        normalizeCompare(b1, '0.51') &&
        normalizeCompare(b2, '0.01531') &&
        normalizeCompare(b3, '0.082')
    );

    var rightAns = "a) 96,3 ; 94 ; 2080. b) 0,51 ; 0,01531 ; 0,082";
    var studentAns = "a) " + a1 + " ; " + a2 + " ; " + a3 + " | b) " + b1 + " ; " + b2 + " ; " + b3;

    var meta = window.MATH_BUILDER_METADATA.bai_tap[0];
    if (window.showMathFeedback) {
        window.showMathFeedback(isCorrect, rightAns, studentAns, meta.guidance, meta.solution);
    }
    if (window.submitMathLesson) {
        window.submitMathLesson(meta.title, isCorrect ? 100 : 0, 'btn-check-51-1', 0, 6, isCorrect ? 6 : 0);
    }
};

