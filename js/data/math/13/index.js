window.distributionState = {
    an: { whole: false, slice: false },
    binh: { whole: false, slice: false },
    chi: { whole: false, slice: false },
    duong: { whole: false, slice: false }
};

window.distributeCake = function(type, element) {
    const plates = ['an', 'binh', 'chi', 'duong'];
    const plateNames = { an: 'plate-an-cakes', binh: 'plate-binh-cakes', chi: 'plate-chi-cakes', duong: 'plate-duong-cakes' };
    
    // Tìm đĩa đầu tiên chưa có loại bánh này
    const targetPlate = plates.find(p => !window.distributionState[p][type]);
    if (!targetPlate) return;
    
    window.distributionState[targetPlate][type] = true;
    element.classList.add('opacity-0', 'pointer-events-none');
    
    // Vẽ bánh lên đĩa tương ứng
    const plateEl = document.getElementById(plateNames[targetPlate]);
    if (plateEl) {
        const wholeSvg = `
            <div class="w-8 h-8">
                <svg class="w-full h-full" viewBox="0 0 100 100">
                    <circle cx="50" cy="50" fill="#f59e0b" r="45" stroke="#d97706" stroke-width="4"></circle>
                    <circle cx="50" cy="50" fill="none" r="35" stroke="#d97706" stroke-dasharray="4,4" stroke-width="2"></circle>
                    <path d="M 50 15 A 35 35 0 0 0 15 50 L 85 50 A 35 35 0 0 0 50 15" fill="none" stroke="#d97706" stroke-width="3"></path>
                    <circle cx="50" cy="50" fill="#d97706" r="10"></circle>
                </svg>
            </div>
        `;
        const sliceSvg = `
            <div class="w-8 h-8">
                <svg class="w-full h-full" viewBox="0 0 100 100">
                    <path d="M 50 50 L 50 5 A 45 45 0 0 1 95 50 Z" fill="#f59e0b" stroke="#d97706" stroke-width="4"></path>
                    <line x1="50" y1="50" x2="50" y2="5" stroke="#d97706" stroke-width="4"></line>
                    <line x1="50" y1="50" x2="95" y2="50" stroke="#d97706" stroke-width="4"></line>
                </svg>
            </div>
        `;
        
        let content = '';
        if (window.distributionState[targetPlate].whole) content += wholeSvg;
        if (window.distributionState[targetPlate].slice) content += sliceSvg;
        plateEl.innerHTML = content;
    }
    
    // Kiểm tra hoàn thành tất cả
    const allDone = plates.every(p => window.distributionState[p].whole && window.distributionState[p].slice);
    if (allDone) {
        const distText = document.getElementById('distribution-text');
        if (distText) distText.classList.remove('hidden');
        const initialCakes = document.getElementById('initial-cakes');
        if (initialCakes) initialCakes.classList.add('opacity-30');
    }
};

window.resetCakeDistribution = function() {
    window.distributionState = {
        an: { whole: false, slice: false },
        binh: { whole: false, slice: false },
        chi: { whole: false, slice: false },
        duong: { whole: false, slice: false }
    };
    
    ['plate-an-cakes', 'plate-binh-cakes', 'plate-chi-cakes', 'plate-duong-cakes'].forEach(id => {
        const el = document.getElementById(id);
        if (el) el.innerHTML = '';
    });
    
    const poolElements = document.querySelectorAll('#whole-cakes-pool > div, #cut-cake-container path');
    poolElements.forEach(el => el.classList.remove('opacity-0', 'pointer-events-none'));
    
    const distText = document.getElementById('distribution-text');
    if (distText) distText.classList.add('hidden');
    const initialCakes = document.getElementById('initial-cakes');
    if (initialCakes) initialCakes.classList.remove('opacity-30', 'hidden');
};

window.animateCakeDistribution = function() {
    window.resetCakeDistribution();
    const plates = ['plate-an-cakes', 'plate-binh-cakes', 'plate-chi-cakes', 'plate-duong-cakes'];
    const wholeCakeSvg = `
        <div class="w-8 h-8">
            <svg class="w-full h-full" viewBox="0 0 100 100">
                <circle cx="50" cy="50" fill="#f59e0b" r="45" stroke="#d97706" stroke-width="4"></circle>
                <circle cx="50" cy="50" fill="none" r="35" stroke="#d97706" stroke-dasharray="4,4" stroke-width="2"></circle>
                <path d="M 50 15 A 35 35 0 0 0 15 50 L 85 50 A 35 35 0 0 0 50 15" fill="none" stroke="#d97706" stroke-width="3"></path>
                <circle cx="50" cy="50" fill="#d97706" r="10"></circle>
            </svg>
        </div>
    `;
    const sliceCakeSvg = `
        <div class="w-8 h-8">
            <svg class="w-full h-full" viewBox="0 0 100 100">
                <path d="M 50 50 L 50 5 A 45 45 0 0 1 95 50 Z" fill="#f59e0b" stroke="#d97706" stroke-width="4"></path>
                <line x1="50" y1="50" x2="50" y2="5" stroke="#d97706" stroke-width="4"></line>
                <line x1="50" y1="50" x2="95" y2="50" stroke="#d97706" stroke-width="4"></line>
            </svg>
        </div>
    `;
    
    plates.forEach(plateId => {
        const plateEl = document.getElementById(plateId);
        if (plateEl) {
            plateEl.innerHTML = wholeCakeSvg + sliceCakeSvg;
        }
    });

    ['an', 'binh', 'chi', 'duong'].forEach(p => {
        window.distributionState[p].whole = true;
        window.distributionState[p].slice = true;
    });

    const poolElements = document.querySelectorAll('#whole-cakes-pool > div, #cut-cake-container path');
    poolElements.forEach(el => el.classList.add('opacity-0', 'pointer-events-none'));

    const initialCakes = document.getElementById('initial-cakes');
    if (initialCakes) initialCakes.classList.add('opacity-30');

    const distText = document.getElementById('distribution-text');
    if (distText) distText.classList.remove('hidden');
};

window.switchB1Tab = function(tabId) {
    const tabA = document.getElementById('b1-tab-a');
    const tabB = document.getElementById('b1-tab-b');
    const btnA = document.getElementById('btn-b1-tab-a');
    const btnB = document.getElementById('btn-b1-tab-b');

    if (!tabA || !tabB || !btnA || !btnB) return;

    if (tabId === 'a') {
        tabA.classList.remove('hidden');
        tabB.classList.add('hidden');
        btnA.className = "px-5 py-2.5 bg-blue-600 text-white font-black rounded-xl shadow-md transition-all";
        btnB.className = "px-5 py-2.5 bg-slate-100 text-blue-600 hover:bg-blue-50 font-black rounded-xl transition-all";
    } else {
        tabA.classList.add('hidden');
        tabB.classList.remove('hidden');
        btnA.className = "px-5 py-2.5 bg-slate-100 text-blue-600 hover:bg-blue-50 font-black rounded-xl transition-all";
        btnB.className = "px-5 py-2.5 bg-blue-600 text-white font-black rounded-xl shadow-md transition-all";
    }
};

