window.clickNode115 = function(nodeId) {
    const isLantern = nodeId.startsWith('node-lan-');
    const isNet = nodeId.startsWith('node-net-');

    if (window._selectedNode115 === nodeId) {
        const el = document.getElementById(nodeId);
        if (el) el.classList.remove('selected');
        window._selectedNode115 = null;
        return;
    }

    let foundMatchKey = null;
    if (isLantern) {
        const key = nodeId.replace('node-lan-', '');
        if (window._matches115[key]) {
            foundMatchKey = key;
        }
    } else {
        const val = nodeId.replace('node-net-', '');
        Object.keys(window._matches115).forEach(k => {
            if (window._matches115[k] === val) {
                foundMatchKey = k;
            }
        });
    }
    if (foundMatchKey) {
        delete window._matches115[foundMatchKey];
        window.redrawLines115();
        return;
    }

    if (!window._selectedNode115) {
        window._selectedNode115 = nodeId;
        const el = document.getElementById(nodeId);
        if (el) el.classList.add('selected');
    } else {
        const prevNode = window._selectedNode115;
        const prevIsLantern = prevNode.startsWith('node-lan-');

        if (prevIsLantern === isLantern) {
            const prevEl = document.getElementById(prevNode);
            if (prevEl) prevEl.classList.remove('selected');

            window._selectedNode115 = nodeId;
            const curEl = document.getElementById(nodeId);
            if (curEl) curEl.classList.add('selected');
            return;
        }

        const prevEl = document.getElementById(prevNode);
        if (prevEl) prevEl.classList.remove('selected');

        const lanKey = prevIsLantern ? prevNode.replace('node-lan-', '') : nodeId.replace('node-lan-', '');
        const netVal = prevIsLantern ? nodeId.replace('node-net-', '') : prevNode.replace('node-net-', '');

        delete window._matches115[lanKey];
        Object.keys(window._matches115).forEach(k => {
            if (window._matches115[k] === netVal) {
                delete window._matches115[k];
            }
        });

        window._matches115[lanKey] = netVal;
        window._selectedNode115 = null;
        window.redrawLines115();
    }
};

window.redrawLines115 = () => {
    const svg = document.getElementById('svg-lines-115');
    if (!svg) return;
    svg.innerHTML = '';
    
    const container = svg.parentElement;
    if (!container) return;
    const containerRect = container.getBoundingClientRect();

    Object.keys(window._matches115).forEach(lanKey => {
        const netVal = window._matches115[lanKey];
        const lanEl = document.getElementById('node-lan-' + lanKey);
        const netEl = document.getElementById('node-net-' + netVal);
        if (!lanEl || !netEl) return;

        const lanRect = lanEl.getBoundingClientRect();
        const netRect = netEl.getBoundingClientRect();

        const x1 = lanRect.left + lanRect.width / 2 - containerRect.left;
        const y1 = lanRect.top + lanRect.height / 2 - containerRect.top;
        const x2 = netRect.left + netRect.width / 2 - containerRect.left;
        const y2 = netRect.top + netRect.height / 2 - containerRect.top;

        const line = document.createElementNS('http://www.w3.org/2000/svg', 'line');
        line.setAttribute('x1', x1);
        line.setAttribute('y1', y1);
        line.setAttribute('x2', x2);
        line.setAttribute('y2', y2);
        line.setAttribute('stroke', '#2563eb');
        line.setAttribute('stroke-width', '4');
        line.setAttribute('stroke-dasharray', '8,4');
        line.setAttribute('stroke-linecap', 'round');
        line.style.filter = 'drop-shadow(1px 1px 1.5px rgba(0,0,0,0.3))';
        svg.appendChild(line);
    });
};

