window.rolls_150 = { r1: 0, r2: 0, r34: 0, r56: 0, total: 0 };

window.rollDice150 = function () {
    const btn = document.getElementById('btn-roll-150');
    const cube = document.getElementById('dice-cube-150');
    if (!btn || !cube) return;

    btn.disabled = true;

    const randX = Math.floor(Math.random() * 3 + 4) * 360;
    const randY = Math.floor(Math.random() * 3 + 4) * 360;
    const val = Math.floor(Math.random() * 6) + 1;

    const rotations = {
        1: { x: 0, y: 0 },
        2: { x: -90, y: 0 },
        3: { x: 0, y: -90 },
        4: { x: 0, y: 90 },
        5: { x: 90, y: 0 },
        6: { x: 180, y: 0 }
    };

    const targetPos = rotations[val];
    cube.style.transform = `rotateX(${randX + targetPos.x}deg) rotateY(${randY + targetPos.y}deg)`;

    setTimeout(() => {
        window.rolls_150.total++;
        if (val === 1) window.rolls_150.r1++;
        else if (val === 2) window.rolls_150.r2++;
        else if (val === 3 || val === 4) window.rolls_150.r34++;
        else window.rolls_150.r56++;

        document.getElementById('roll-total-150').innerText = window.rolls_150.total;
        document.getElementById('res-150-1').innerText = window.rolls_150.r1;
        document.getElementById('res-150-2').innerText = window.rolls_150.r2;
        document.getElementById('res-150-34').innerText = window.rolls_150.r34;
        document.getElementById('res-150-56').innerText = window.rolls_150.r56;

        btn.disabled = false;
    }, 1000);
};

window.check_150_1 = function () {
    if (window.rolls_150.total === 0) {
        window.UI.showToast("Em hãy gieo xúc xắc để có số liệu thực tế đã nhé!", "error");
        return;
    }

    const v1 = parseInt(document.getElementById('in-150-1-1').value);
    const v2 = parseInt(document.getElementById('in-150-1-2').value); // ID corrected from -2-1 to -1-2 in refactor
    const v3 = parseInt(document.getElementById('in-150-1-3').value); // ID corrected 
    const v4 = parseInt(document.getElementById('in-150-1-4').value); // ID corrected
    const most = (document.getElementById('in-150-1-most').value || "").toLowerCase();
    const ratioUp = parseInt(document.getElementById('in-150-1-ratio-up').value);
    const ratioDown = parseInt(document.getElementById('in-150-1-ratio-down').value);

    const groups = [
        { name: 'quét và lau sàn', val: window.rolls_150.r1 },
        { name: 'lau cửa', val: window.rolls_150.r2 },
        { name: 'kê bàn ghế', val: window.rolls_150.r34 },
        { name: 'trang trí lớp', val: window.rolls_150.r56 }
    ];
    const maxVal = Math.max(...groups.map(g => g.val));
    const winners = groups.filter(g => g.val === maxVal).map(g => g.name);

    let correctCount = 0;
    if (v1 === window.rolls_150.r1) correctCount++;
    if (v2 === window.rolls_150.r2) correctCount++;
    if (v3 === window.rolls_150.r34) correctCount++;
    if (v4 === window.rolls_150.r56) correctCount++;
    if (winners.some(w => most === w)) correctCount++;
    if (ratioUp === window.rolls_150.r1 && ratioDown === window.rolls_150.total) correctCount++;

    const totalQuestions = 6;
    const isCorrect = correctCount === totalQuestions;

    let sol = `<div class='p-8 bg-blue-50 rounded-[3rem] border-2 border-blue-100 font-bold text-slate-700 text-3xl space-y-4'>
        <p>✅ Kết quả thực tế sĩ số ${window.rolls_150.total} bạn: <br>
        - Quét và lau sàn: <b>${window.rolls_150.r1} bạn</b> <br>
        - Lau cửa: <b>${window.rolls_150.r2} bạn</b> <br>
        - Kê bàn ghế: <b>${window.rolls_150.r34} bạn</b> <br>
        - Trang trí lớp: <b>${window.rolls_150.r56} bạn</b></p>
        <p>✅ Nhóm đông nhất: <b>${winners.join(' hoặc ')}</b>.</p>
        <p>✅ Tỉ số mặt 1 chấm: <b>${window.rolls_150.r1}/${window.rolls_150.total}</b>.</p>
    </div>`;

    window.showMathFeedback(isCorrect, `${window.rolls_150.r1}, ${window.rolls_150.r2}, ${window.rolls_150.r34}, ${window.rolls_150.r56}`, "", "Học sinh gieo xúc xắc, ghi kết quả vào bảng và so sánh số lượng.", sol);
    if (window.submitMathLesson) {
        window.submitMathLesson("Bài 1. Chia nhóm xúc xắc | Tổng: " + window.rolls_150.total, isCorrect ? 100 : Math.round((correctCount / totalQuestions) * 100), "btn-check-150-1", 0, totalQuestions, correctCount);
    }
};

