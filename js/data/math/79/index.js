window.spinPlay79 = function() {
    if (window._spinners79.winner !== '' || window._spinners79.turn === 'wait') return;
    
    // Check if it's Robot's turn - prevent human from spinning
    if (window._spinners79.mode === 'robot' && window._spinners79.turn === 'p2') return;

    const val1 = window._spinners79.wheel1[Math.floor(Math.random() * window._spinners79.wheel1.length)];
    const val2 = window._spinners79.wheel2[Math.floor(Math.random() * window._spinners79.wheel2.length)];
    
    window._spinners79.current1 = val1;
    window._spinners79.current2 = val2;
    
    document.getElementById('spin-val-1').innerText = String(val1).replace('.', ',');
    document.getElementById('spin-val-2').innerText = String(val2).replace('.', ',');
    
    const targetProduct = val1 * val2;
    const productStr = String(parseFloat(targetProduct.toFixed(3))).replace('.', ',');
    
    // Find index matching targetProduct
    const cellVals = [12, 10, 2.65, 7.5, 4.24, 2.75, 1.166, 3.3, 6.25];
    let targetIdx = -1;
    for (let i = 0; i < cellVals.length; i++) {
        if (Math.abs(cellVals[i] - targetProduct) < 0.001) {
            targetIdx = i;
            break;
        }
    }

    const activeTurn = window._spinners79.turn;
    const activeName = activeTurn === 'p1' ? window._spinners79.player1 : window._spinners79.player2;
    const symbol = activeTurn === 'p1' ? '❌' : '⭕';

    // If the active player already owns the target cell: pass turn
    if (targetIdx !== -1 && window._spinners79.boardClaims[targetIdx] === activeTurn) {
        const opponentName = activeTurn === 'p1' ? window._spinners79.player2 : window._spinners79.player1;
        const opponentSymbol = activeTurn === 'p1' ? '⭕' : '❌';
        
        document.getElementById('game-status-79').innerHTML = `Quay vào ô <strong class="text-blue-600">${productStr}</strong> đã sở hữu!<br><span class="text-orange-600">Lượt chơi tự động chuyển sang ${opponentName}.</span>`;
        window._spinners79.isSpun = false;
        window._spinners79.turn = 'wait';

        setTimeout(() => {
            if (window._spinners79.mode === 'robot') {
                window._spinners79.turn = 'p2';
                document.getElementById('game-status-79').innerHTML = `🤖 <strong class="text-slate-600">Đến lượt Rô-bốt...</strong>`;
                setTimeout(window.robotTurn79, 1500);
            } else {
                window._spinners79.turn = (activeTurn === 'p1') ? 'p2' : 'p1';
                document.getElementById('game-status-79').innerHTML = `Đến lượt <strong class="text-blue-600">${opponentName} (${opponentSymbol})</strong>. Hãy bấm "Xoay vòng quay"!`;
            }
        }, 2000);
        return;
    }

    window._spinners79.isSpun = true;
    document.getElementById('game-status-79').innerHTML = `Tích cần tìm: <strong class="text-blue-600 text-lg">${productStr}</strong>.<br><span class="text-slate-700">${activeName} (${symbol})</span> hãy click vào ô chứa kết quả tương ứng để giành ô!`;
};

window.claimCell79 = function(idx, valStr) {
    if (window._spinners79.winner !== '' || !window._spinners79.isSpun || window._spinners79.turn === 'wait') return;
    if (window._spinners79.mode === 'robot' && window._spinners79.turn === 'p2') return; // Robot's turn

    const targetProduct = window._spinners79.current1 * window._spinners79.current2;
    const cellVal = parseFloat(valStr.replace(',', '.'));
    
    if (Math.abs(targetProduct - cellVal) < 0.001) {
        // Correct calculation
        const activeTurn = window._spinners79.turn;
        
        // Cannot replace own piece
        if (window._spinners79.boardClaims[idx] === activeTurn) {
            document.getElementById('game-status-79').innerHTML = `<span class="text-orange-600">Bạn đã chiếm ô này rồi! Hãy chọn ô khác.</span>`;
            return;
        }

        // Claim cell
        window._spinners79.boardClaims[idx] = activeTurn;
        const cell = document.getElementById('board-cell-' + idx);
        
        if (activeTurn === 'p1') {
            cell.className = "bg-blue-600 text-white rounded-2xl font-black text-lg flex items-center justify-center cursor-pointer shadow-md scale-105 transition-all duration-300 border-2 border-blue-400";
            cell.innerHTML = `❌<br>${valStr}`;
        } else {
            cell.className = "bg-red-500 text-white rounded-2xl font-black text-lg flex items-center justify-center cursor-pointer shadow-md scale-105 transition-all duration-300 border-2 border-red-300";
            cell.innerHTML = `⭕<br>${valStr}`;
        }

        // Check win
        if (window.checkWin79(activeTurn)) {
            const activeName = activeTurn === 'p1' ? window._spinners79.player1 : window._spinners79.player2;
            document.getElementById('game-status-79').innerHTML = `🎉 <strong class="text-emerald-600 text-lg">${activeName} đã giành chiến thắng!</strong>`;
            window._spinners79.winner = activeTurn;
            return;
        }

        // Check Draw
        if (window._spinners79.boardClaims.every(c => c !== '')) {
            document.getElementById('game-status-79').innerHTML = `<strong class="text-slate-600 text-lg">Trò chơi kết thúc với tỉ số Hòa!</strong>`;
            window._spinners79.winner = 'draw';
            return;
        }

        // Switch turn
        window._spinners79.isSpun = false;
        if (window._spinners79.mode === 'robot') {
            window._spinners79.turn = 'p2';
            document.getElementById('game-status-79').innerHTML = `🤖 <strong class="text-slate-600">Đến lượt Rô-bốt...</strong>`;
            setTimeout(window.robotTurn79, 1500);
        } else {
            window._spinners79.turn = (activeTurn === 'p1') ? 'p2' : 'p1';
            const nextName = window._spinners79.turn === 'p1' ? window._spinners79.player1 : window._spinners79.player2;
            const nextSymbol = window._spinners79.turn === 'p1' ? '❌' : '⭕';
            document.getElementById('game-status-79').innerHTML = `Đến lượt <strong class="text-blue-600">${nextName} (${nextSymbol})</strong>. Hãy bấm "Xoay vòng quay"!`;
        }
    } else {
        document.getElementById('game-status-79').innerHTML = "❌ <span class='text-red-500'>Tính kết quả hoặc chọn ô chưa đúng!</span> Hãy thử lại.";
    }
};

window.robotTurn79 = function() {
    if (window._spinners79.winner !== '' || window._spinners79.turn !== 'p2') return;

    // Robot spins
    const val1 = window._spinners79.wheel1[Math.floor(Math.random() * window._spinners79.wheel1.length)];
    const val2 = window._spinners79.wheel2[Math.floor(Math.random() * window._spinners79.wheel2.length)];
    
    window._spinners79.current1 = val1;
    window._spinners79.current2 = val2;
    
    document.getElementById('spin-val-1').innerText = String(val1).replace('.', ',');
    document.getElementById('spin-val-2').innerText = String(val2).replace('.', ',');

    const targetProduct = val1 * val2;
    const productStr = String(parseFloat(targetProduct.toFixed(3))).replace('.', ',');
    const cellVals = [12, 10, 2.65, 7.5, 4.24, 2.75, 1.166, 3.3, 6.25];
    
    // Find index matching targetProduct
    let targetIdx = -1;
    for (let i = 0; i < cellVals.length; i++) {
        if (Math.abs(cellVals[i] - targetProduct) < 0.001) {
            targetIdx = i;
            break;
        }
    }

    if (targetIdx !== -1) {
        if (window._spinners79.boardClaims[targetIdx] === 'p2') {
            // Robot spun its own cell! Skip turn.
            document.getElementById('game-status-79').innerHTML = `🤖 Rô-bốt quay vào ô <strong class="text-red-500">${productStr}</strong> đã sở hữu!<br>Lượt chơi tự động chuyển sang <strong class="text-blue-600">${window._spinners79.player1}</strong>.`;
            setTimeout(() => {
                window._spinners79.turn = 'p1';
                window._spinners79.isSpun = false;
                document.getElementById('game-status-79').innerHTML = `Đến lượt <strong class="text-blue-600">${window._spinners79.player1} (❌)</strong>. Hãy bấm "Xoay vòng quay"!`;
            }, 2000);
            return;
        }

        // Can replace human piece
        window._spinners79.boardClaims[targetIdx] = 'p2';
        const cell = document.getElementById('board-cell-' + targetIdx);
        
        cell.className = "bg-red-500 text-white rounded-2xl font-black text-lg flex items-center justify-center cursor-pointer shadow-md scale-105 transition-all duration-300 border-2 border-red-300";
        cell.innerHTML = `🤖<br>${productStr}`;

        // Check Robot Win
        if (window.checkWin79('p2')) {
            document.getElementById('game-status-79').innerHTML = `🤖 <strong class="text-red-500 text-lg">Rô-bốt đã thắng!</strong> Cố gắng hơn lần sau nhé.`;
            window._spinners79.winner = 'p2';
            return;
        }

        // Check Draw
        if (window._spinners79.boardClaims.every(c => c !== '')) {
            document.getElementById('game-status-79').innerHTML = `<strong class="text-slate-600 text-lg">Trò chơi kết thúc với tỉ số Hòa!</strong>`;
            window._spinners79.winner = 'draw';
            return;
        }
    }

    // Back to user
    window._spinners79.turn = 'p1';
    window._spinners79.isSpun = false;
    document.getElementById('game-status-79').innerHTML = `Đến lượt <strong class="text-blue-600">${window._spinners79.player1} (❌)</strong>. Hãy bấm "Xoay vòng quay"!`;
};

window.checkWin79 = function(player) {
    const lines = [
        [0, 1, 2], [3, 4, 5], [6, 7, 8], // Rows
        [0, 3, 6], [1, 4, 7], [2, 5, 8], // Cols
        [0, 4, 8], [2, 4, 6]             // Diag
    ];
    return lines.some(line => {
        return line.every(idx => window._spinners79.boardClaims[idx] === player);
    });
};

