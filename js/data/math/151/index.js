window.check_151_2 = function () {
    const counts = [
        parseInt(document.getElementById('in-151-2-count-1').value),
        parseInt(document.getElementById('in-151-2-count-2').value),
        parseInt(document.getElementById('in-151-2-count-3').value),
        parseInt(document.getElementById('in-151-2-count-4').value),
        parseInt(document.getElementById('in-151-2-count-5').value)
    ];

    const ans1 = parseInt(document.getElementById('in-151-2-ans1').value);
    const ans2 = parseInt(document.getElementById('in-151-2-ans2').value);
    const ans3 = parseFloat(document.getElementById('in-151-2-ans3').value);

    if (counts.some(isNaN)) {
        window.UI.showToast("Em hãy điền đầy đủ số bạn cho mỗi mức điểm nhé!", "error");
        return;
    }

    const totalStudents = counts.reduce((a, b) => a + b, 0);
    if (totalStudents === 0) {
        window.UI.showToast("Tổng số bạn phải lớn hơn 0!", "error");
        return;
    }

    const totalPoints = counts.reduce((sum, count, i) => sum + (count * (i + 1)), 0);
    const expectedAvg = (totalPoints / totalStudents).toFixed(1);

    const maxCount = Math.max(...counts);
    const modes = counts.map((c, i) => c === maxCount ? (i + 1) : null).filter(v => v !== null);

    const isCorrect = (ans1 === counts[4]) && (modes.includes(ans2)) && (Math.abs(ans3 - parseFloat(expectedAvg)) < 0.2);

    const rightAnswer = `Rất hài lòng: ${counts[4]} bạn; Điểm nhiều nhất: ${modes.join(' hoặc ')}; Trung bình: ${expectedAvg}`;
    const guidance = `Em hãy xem lại bảng thống kê ở câu a:
        <br>- Mức "Rất hài lòng" tương ứng với cột 5 điểm.
        <br>- Điểm xuất hiện nhiều nhất là điểm có số lượng bạn chọn cao nhất trong bảng.
        <br>- Để tính điểm trung bình, em lấy tổng điểm của tất cả các bạn chia cho tổng số bạn nhé!`;
    const solution = `<div class='space-y-6'>
        <p class='text-emerald-600 font-bold'>🌈 Thật ấn tượng! Em đã thực hiện các phép tính thống kê rất tốt.</p>
        <div class='bg-white p-6 rounded-[2rem] shadow-inner border border-blue-50 text-blue-900'>
            <p>• Số bạn Rất hài lòng (5 điểm): <b>${counts[4]} bạn</b>.</p>
            <p>• Điểm xuất hiện nhiều nhất: <b>${modes.join(' hoặc ')} điểm</b>.</p>
            <p>• Tổng điểm của nhóm: ${totalPoints} điểm.</p>
            <p>• Tổng số bạn khảo sát: <b>${totalStudents} bạn</b>.</p>
            <div class='mt-4 p-4 bg-blue-50 rounded-xl border-l-8 border-blue-400'>
                <p class='font-bold text-blue-800'>Phép tính trung bình:</p>
                <p>${totalPoints} : ${totalStudents} = <b>${expectedAvg} (điểm)</b></p>
            </div>
        </div>
    </div>`;

    window.showMathFeedback(isCorrect, rightAnswer, `${ans1}, ${ans2}, ${ans3}`, guidance, solution);
    if (window.submitMathLesson) {
        window.submitMathLesson("Bài 2. Khảo sát hài lòng", isCorrect ? 100 : 0, "btn-check-151-2", 0, 3, isCorrect ? 3 : 0);
    }
};

