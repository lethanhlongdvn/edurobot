let selected_58_bt2_val = "";

window.select_58_bt2 = function(val) {
    selected_58_bt2_val = val;
    // Reset all options border
    ['A', 'B', 'C', 'D'].forEach(opt => {
        const btn = document.getElementById(`opt-58-2-${opt}`);
        if (btn) {
            btn.classList.remove('border-blue-500', 'bg-blue-50/50');
            btn.classList.add('border-slate-200');
        }
    });
    // Set active style to selected
    const activeBtn = document.getElementById(`opt-58-2-${val}`);
    if (activeBtn) {
        activeBtn.classList.remove('border-slate-200');
        activeBtn.classList.add('border-blue-500', 'bg-blue-50/50');
    }
};

window.toggleSolution = function(id) {
    const el = document.getElementById(id);
    if (el) {
        el.classList.toggle('hidden');
    }
};

window.check_58_bt1 = function() {
    const valA = document.getElementById('ans-58-1-a').value.trim();
    const valB = document.getElementById('ans-58-1-b').value.trim();

    const isCorrectA = valA === "6";
    const isCorrectB = valB === "20";

    const correctCount = (isCorrectA ? 1 : 0) + (isCorrectB ? 1 : 0);
    const isCorrect = correctCount === 2;

    const rightAns = "a) 6 <br> b) 20";
    const studentAns = `a) ${valA || "Chưa điền"} <br> b) ${valB || "Chưa điền"}`;

    const meta = window.MATH_BUILDER_METADATA.bai_tap[0];
    if (window.showMathFeedback) {
        window.showMathFeedback(isCorrect, rightAns, studentAns, meta.guidance, meta.solution);
    }
    if (window.submitMathLesson) {
        window.submitMathLesson(meta.title, isCorrect ? 100 : (correctCount * 50), 'btn-check-58-bt1', 0, 2, correctCount);
    }
};

