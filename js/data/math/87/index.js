window.check_87_bt1 = function() {
    const answers = metadata.bai_tap[0].answers;
    const ids = [
        'inp-87-bt1-1', 'inp-87-bt1-2', 'inp-87-bt1-3', 'inp-87-bt1-4', 'inp-87-bt1-5', 'inp-87-bt1-6',
        'inp-87-bt1-7', 'inp-87-bt1-8', 'inp-87-bt1-9', 'inp-87-bt1-10', 'inp-87-bt1-11', 'inp-87-bt1-12'
    ];
    let correctCount = 0;
    const totalQuestions = ids.length;

    for (let i = 0; i < totalQuestions; i++) {
        let val = document.getElementById(ids[i]).value.trim().replace(',', '.');
        // Cho phép học sinh gõ dư số 0 ở cuối số thập phân ví dụ: 5.360 thay vì 5.36
        const parsedVal = parseFloat(val);
        const parsedAns = parseFloat(answers[i]);
        if (!isNaN(parsedVal) && parsedVal === parsedAns) {
            correctCount++;
        }
    }

    const isCorrect = (correctCount === totalQuestions);

    const rightAnswer = "a) 5.36; 6.205; 6.34; 0.565; 0.75; 3.54; b) 5.18; 48.09; 2.36; 3.45; 0.8; 0.52";
    const studentAnswer = `Học sinh điền đúng ${correctCount}/${totalQuestions} ô.`;
    const guidance = metadata.bai_tap[0].guidance;
    const solution = metadata.bai_tap[0].solution;

    window.showMathFeedback(isCorrect, rightAnswer, studentAnswer, guidance, solution);

    if (window.submitMathLesson) {
        window.submitMathLesson("Bài 1: Tìm số thập phân thích hợp", isCorrect ? 100 : 0, 'btn-check-87-bt1', 0, totalQuestions, correctCount);
    }
};

