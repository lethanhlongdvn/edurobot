// ĐĂNG KÝ HÀM CHUYỂN TAB VÀ SUBTAB
window.switchTab_46 = function(tabIndex) {
    // Ẩn tất cả tab chính
    for (let i = 1; i <= 4; i++) {
        let content = document.getElementById('tab-content-46-' + i);
        if (content) content.classList.add('hidden');
        let btn = document.getElementById('tab-btn-46-' + i);
        if (btn) btn.className = "px-5 py-2.5 rounded-full font-black text-xs md:text-base transition-all text-blue-600 hover:bg-blue-100/50";
    }

    // Hiển thị tab đang chọn
    let activeContent = document.getElementById('tab-content-46-' + tabIndex);
    if (activeContent) activeContent.classList.remove('hidden');
    let activeBtn = document.getElementById('tab-btn-46-' + tabIndex);
    if (activeBtn) activeBtn.className = "px-5 py-2.5 rounded-full font-black text-xs md:text-base transition-all bg-blue-600 text-white shadow";

    // Kích hoạt subtab tương ứng để tránh bị ẩn do chéo tab
    if (tabIndex === 1) {
        window.switchSubTab_46('1a');
    } else if (tabIndex === 2) {
        window.switchSubTab_46('2a');
    }
};

