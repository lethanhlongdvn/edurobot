window.matching81State = {
    top: null,
    bottom: null,
    connections: []
};

window.selectMatchingDot81 = function(element, side, id, x, y) {
    const state = window.matching81State;
    
    // Nếu bấm lại chính nút đang chọn -> Bỏ chọn
    if (state[side] && state[side].id === id) {
        element.classList.remove('ring-4', side === 'top' ? 'ring-blue-400' : 'ring-indigo-400', 'scale-125');
        state[side] = null;
        return;
    }
    
    // Bỏ chọn nút cũ cùng một bên
    document.querySelectorAll(side === 'top' ? '#matching-container-81-bt1 button[id^="dot-top-"]' : '#matching-container-81-bt1 button[id^="dot-bottom-"]').forEach(btn => {
        btn.classList.remove('ring-4', 'ring-blue-400', 'ring-indigo-400', 'scale-125');
    });
    
    element.classList.add('ring-4', side === 'top' ? 'ring-blue-400' : 'ring-indigo-400', 'scale-125');
    state[side] = { id, x, y, el: element };
    
    // Nếu đã chọn đủ cả 2 bên -> Thực hiện kết nối
    if (state.top && state.bottom) {
        // Loại bỏ kết nối cũ của điểm trên hoặc điểm dưới để đảm bảo quan hệ 1-1
        state.connections = state.connections.filter(conn => conn.topId !== state.top.id && conn.bottomId !== state.bottom.id);
        
        state.connections.push({
            topId: state.top.id,
            bottomId: state.bottom.id,
            x1: state.top.x,
            y1: state.top.y,
            x2: state.bottom.x,
            y2: state.bottom.y
        });
        
        // Reset trạng thái chọn
        state.top.el.classList.remove('ring-4', 'ring-blue-400', 'scale-125');
        state.bottom.el.classList.remove('ring-4', 'ring-indigo-400', 'scale-125');
        
        state.top = null;
        state.bottom = null;
        
        window.redrawMatching81Lines();
    }
};

window.redrawMatching81Lines = function() {
    const svg = document.getElementById('svg-connections-81-bt1');
    if (!svg) return;
    svg.innerHTML = '';
    const state = window.matching81State;
    state.connections.forEach(conn => {
        const line = document.createElementNS('http://www.w3.org/2000/svg', 'line');
        line.setAttribute('x1', conn.x1 + '%');
        line.setAttribute('y1', conn.y1 + '%');
        line.setAttribute('x2', conn.x2 + '%');
        line.setAttribute('y2', conn.y2 + '%');
        line.setAttribute('stroke', '#2563eb');
        line.setAttribute('stroke-width', '4');
        line.setAttribute('stroke-linecap', 'round');
        svg.appendChild(line);
    });
};

window.resetMatching81 = function() {
    window.matching81State = { top: null, bottom: null, connections: [] };
    const svg = document.getElementById('svg-connections-81-bt1');
    if (svg) svg.innerHTML = '';
    document.querySelectorAll('#matching-container-81-bt1 button').forEach(btn => {
        btn.classList.remove('ring-4', 'ring-blue-400', 'ring-indigo-400', 'scale-125');
    });
};

