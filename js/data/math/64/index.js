window.canvasStates = {};

window.initCanvas64 = function(id) {
    const canvas = document.getElementById('canvas-' + id);
    if (!canvas) return;

    const ctx = canvas.getContext('2d');
    const rect = canvas.getBoundingClientRect();
    
    // Khóa cứng kích thước canvas
    canvas.width = rect.width || 500;
    canvas.height = rect.height || 375;

    // Thiết lập state vẽ ban đầu
    window.canvasStates[id] = {
        ctx: ctx,
        width: canvas.width,
        height: canvas.height,
        isDrawing: false,
        lastX: 0,
        lastY: 0,
        drawnObjects: [], // Lưu trữ các thao tác vẽ tự động
        colorized: false
    };

    // Vẽ lưới nền nhẹ
    window.drawCanvasGrid64(id);

    // Hỗ trợ vẽ bút chì tự do bằng chuột/cảm ứng
    const getPos = (e) => {
        const cRect = canvas.getBoundingClientRect();
        const clientX = e.touches ? e.touches[0].clientX : e.clientX;
        const clientY = e.touches ? e.touches[0].clientY : e.clientY;
        return {
            x: ((clientX - cRect.left) / cRect.width) * canvas.width,
            y: ((clientY - cRect.top) / cRect.height) * canvas.height
        };
    };

    const startDraw = (e) => {
        window.canvasStates[id].isDrawing = true;
        const pos = getPos(e);
        window.canvasStates[id].lastX = pos.x;
        window.canvasStates[id].lastY = pos.y;
    };

    const draw = (e) => {
        if (!window.canvasStates[id].isDrawing) return;
        const pos = getPos(e);
        ctx.beginPath();
        ctx.strokeStyle = '#3b82f6';
        ctx.lineWidth = 2;
        ctx.lineCap = 'round';
        ctx.moveTo(window.canvasStates[id].lastX, window.canvasStates[id].lastY);
        ctx.lineTo(pos.x, pos.y);
        ctx.stroke();
        window.canvasStates[id].lastX = pos.x;
        window.canvasStates[id].lastY = pos.y;
    };

    const stopDraw = () => {
        window.canvasStates[id].isDrawing = false;
    };

    canvas.addEventListener('mousedown', startDraw);
    canvas.addEventListener('mousemove', draw);
    canvas.addEventListener('mouseup', stopDraw);
    canvas.addEventListener('mouseleave', stopDraw);

    canvas.addEventListener('touchstart', (e) => { e.preventDefault(); startDraw(e); });
    canvas.addEventListener('touchmove', (e) => { e.preventDefault(); draw(e); });
    canvas.addEventListener('touchend', stopDraw);
};

window.drawCanvasGrid64 = function(id) {
    const state = window.canvasStates[id];
    if (!state) return;
    const { ctx, width, height } = state;
    
    ctx.strokeStyle = '#f1f5f9';
    ctx.lineWidth = 1;
    const size = 30; // 30px mỗi ô
    for (let x = 0; x < width; x += size) {
        ctx.beginPath();
        ctx.moveTo(x, 0);
        ctx.lineTo(x, height);
        ctx.stroke();
    }
    for (let y = 0; y < height; y += size) {
        ctx.beginPath();
        ctx.moveTo(0, y);
        ctx.lineTo(width, y);
        ctx.stroke();
    }
};

window.clearCanvas64 = function(id) {
    const state = window.canvasStates[id];
    if (!state) return;
    const { ctx, width, height } = state;
    ctx.clearRect(0, 0, width, height);
    state.drawnObjects = [];
    state.colorized = false;
    window.drawCanvasGrid64(id);
};

// Vẽ tự động hình tròn Bài 1
window.autoDrawCircle64 = function(name, radiusPx) {
    const state = window.canvasStates['64-1'];
    if (!state) return;
    const { ctx, width, height } = state;

    // Điểm tâm O nằm bên trái, điểm tâm I nằm bên phải (nằm chính xác trên lưới ô vuông 30px)
    const cx = (name === 'O') ? 150 : 330;
    const cy = 180;

    // Hiệu ứng vẽ com pa chuyển động tròn
    let angle = 0;
    ctx.strokeStyle = (name === 'O') ? '#2563eb' : '#059669';
    ctx.lineWidth = 2.5;

    // Vẽ điểm tâm
    ctx.beginPath();
    ctx.arc(cx, cy, 4, 0, Math.PI * 2);
    ctx.fillStyle = '#ef4444';
    ctx.fill();
    ctx.font = 'black 14px sans-serif';
    ctx.fillText(name, cx - 12, cy - 10);

    // Vẽ bán kínhOM / IN tĩnh
    ctx.beginPath();
    ctx.moveTo(cx, cy);
    ctx.lineTo(cx + radiusPx, cy);
    ctx.strokeStyle = '#cbd5e1';
    ctx.stroke();

    ctx.font = 'bold 10px sans-serif';
    ctx.fillStyle = '#64748b';
    ctx.fillText(name === 'O' ? "3 cm" : "3,5 cm", cx + radiusPx / 3, cy - 5);

    const animate = () => {
        if (angle >= Math.PI * 2) {
            state.drawnObjects.push({ type: 'circle', name: name, cx: cx, cy: cy, r: radiusPx });
            return;
        }
        ctx.beginPath();
        ctx.arc(cx, cy, radiusPx, angle, angle + 0.1);
        ctx.strokeStyle = (name === 'O') ? '#2563eb' : '#059669';
        ctx.stroke();
        angle += 0.1;
        requestAnimationFrame(animate);
    };
    animate();
};

// Vẽ tự động từng bước Bài 2
window.drawStep64 = function(step) {
    const state = window.canvasStates['64-2'];
    if (!state) return;
    const { ctx, width, height } = state;

    // Thiết lập tọa độ tâm cố định trên lưới ô vuông (bội số của 30)
    const sx = 180;
    const sy = 180;

    if (step === 1) {
        window.clearCanvas64('64-2');
        // Bước 1: Vẽ tâm S và 2 đường tròn (25 mm = 75px, 7 cm = 210px)
        ctx.beginPath();
        ctx.arc(sx, sy, 4, 0, Math.PI * 2);
        ctx.fillStyle = '#ef4444';
        ctx.fill();
        ctx.font = 'black 14px sans-serif';
        ctx.fillText('S', sx - 12, sy - 10);

        // Mặt trời 75px
        ctx.beginPath();
        ctx.arc(sx, sy, 75, 0, Math.PI * 2);
        ctx.strokeStyle = '#ef4444';
        ctx.stroke();

        // Quỹ đạo Trái Đất 210px (Nét đứt)
        ctx.beginPath();
        ctx.setLineDash([4, 4]);
        ctx.arc(sx, sy, 210, 0, Math.PI * 2);
        ctx.strokeStyle = '#94a3b8';
        ctx.stroke();
        ctx.setLineDash([]); // Reset nét liền

        state.drawnObjects.push({ step: 1 });
    }
    else if (step === 2) {
        // Bước 2: Lấy điểm E nằm ngang bên phải trên đường tròn 210px
        const ex = sx + 210; // 180 + 210 = 390 (bội số của 30)
        const ey = sy;       // 180

        ctx.beginPath();
        ctx.arc(ex, ey, 4, 0, Math.PI * 2);
        ctx.fillStyle = '#2563eb';
        ctx.fill();
        ctx.font = 'black 14px sans-serif';
        ctx.fillText('E', ex - 12, ey - 10);

        // Trái Đất 45px (15 mm)
        ctx.beginPath();
        ctx.arc(ex, ey, 45, 0, Math.PI * 2);
        ctx.strokeStyle = '#2563eb';
        ctx.stroke();

        // Quỹ đạo Mặt Trăng 90px (3 cm)
        ctx.beginPath();
        ctx.setLineDash([3, 3]);
        ctx.arc(ex, ey, 90, 0, Math.PI * 2);
        ctx.strokeStyle = '#94a3b8';
        ctx.stroke();
        ctx.setLineDash([]);

        state.drawnObjects.push({ step: 2, ex: ex, ey: ey });
    }
    else if (step === 3) {
        // Tìm E từ mảng vẽ trước đó
        const step2 = state.drawnObjects.find(o => o.step === 2);
        if (!step2) {
            alert("Em hãy vẽ Bước 1 và Bước 2 trước nhé!");
            return;
        }
        const { ex, ey } = step2;

        // Bước 3: Lấy điểm M nằm ngang bên trái của E trên đường tròn 90px
        const mx = ex - 90; // 390 - 90 = 300 (bội số của 30)
        const my = ey;      // 180

        ctx.beginPath();
        ctx.arc(mx, my, 3, 0, Math.PI * 2);
        ctx.fillStyle = '#eab308';
        ctx.fill();
        ctx.font = 'black 14px sans-serif';
        ctx.fillText('M', mx - 12, my - 10);

        // Mặt trăng 36px (12 mm)
        ctx.beginPath();
        ctx.arc(mx, my, 36, 0, Math.PI * 2);
        ctx.strokeStyle = '#eab308';
        ctx.stroke();

        state.drawnObjects.push({ step: 3, mx: mx, my: my });
    }
};

window.colorizeModel64 = function() {
    const state = window.canvasStates['64-2'];
    if (!state) return;
    const { ctx, width, height } = state;

    const step1 = state.drawnObjects.find(o => o.step === 1);
    const step2 = state.drawnObjects.find(o => o.step === 2);
    const step3 = state.drawnObjects.find(o => o.step === 3);

    if (!step1 || !step2 || !step3) {
        alert("Em hãy hoàn thành vẽ 3 bước trước khi tô màu nhé!");
        return;
    }

    const sx = 180;
    const sy = 180;
    const { ex, ey } = step2;
    const { mx, my } = step3;

    // Tô màu đỏ Mặt Trời (75px)
    ctx.beginPath();
    ctx.arc(sx, sy, 75, 0, Math.PI * 2);
    ctx.fillStyle = '#ef4444';
    ctx.fill();

    // Tô màu xanh dương Trái Đất (45px)
    ctx.beginPath();
    ctx.arc(ex, ey, 45, 0, Math.PI * 2);
    ctx.fillStyle = '#3b82f6';
    ctx.fill();

    // Tô màu vàng Mặt Trăng (36px)
    ctx.beginPath();
    ctx.arc(mx, my, 36, 0, Math.PI * 2);
    ctx.fillStyle = '#f59e0b';
    ctx.fill();

    state.colorized = true;
};

