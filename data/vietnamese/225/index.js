window.checkLt225 = function() {
    const evA = document.getElementById('sel-225-evA').value; // 8 chuyến tàu (tháng 3-8/1939) -> Thứ tự 2
    const evB = document.getElementById('sel-225-evB').value; // Bay sang Tiệp Khắc (tháng 12/1938) -> Thứ tự 1
    const evC = document.getElementById('sel-225-evC').value; // Biên giới đóng (1/9/1939) -> Thứ tự 3
    const evD = document.getElementById('sel-225-evD').value; // Hội ngộ truyền hình (1988) -> Thứ tự 4
    const evE = document.getElementById('sel-225-evE').value; // Qua đời, dựng tượng (2015) -> Thứ tự 5
    const fb = document.getElementById('fb-order-225');
    fb.classList.remove('hidden');

    if (!evA || !evB || !evC || !evD || !evE) {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-orange-100 text-orange-800 border border-orange-200 mt-4";
        fb.innerHTML = "⚠️ Em vui lòng chọn số thứ tự cho cả 5 sự kiện nhé!";
        return;
    }

    if (evB === '1' && evA === '2' && evC === '3' && evD === '4' && evE === '5') {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-green-100 text-green-800 border border-green-200 mt-4";
        fb.innerHTML = "🌟 Xuất sắc! Em đã sắp xếp chính xác 100% dòng sự kiện lịch sử vĩ đại trong cuộc đời cứu người thầm lặng của ông Uyn-tơn.";
        if (typeof window.playAudioHelper === 'function') { window.playAudioHelper('correct'); }
        
        // Gọi lưu điểm
        if (typeof window.submitMathLesson === 'function') {
            window.submitMathLesson("Đọc Tiết 225: Sắp xếp sự kiện", 100, "ex-225-order", 1, 1, 1);
        }
    } else {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-red-100 text-red-800 border border-red-200 mt-4";
        fb.innerHTML = "❌ Chưa chính xác rồi. Em hãy đọc kĩ lại mốc thời gian trong bài học và sắp xếp lại nhé!";
        if (typeof window.playAudioHelper === 'function') { window.playAudioHelper('incorrect'); }
    }
};

