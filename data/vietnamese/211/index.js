window.checkEx1_211 = function() {
    const giangiao = document.getElementById('sel-211-1-giangiao').value;
    const betong = document.getElementById('sel-211-1-betong').value;
    const ngoinha = document.getElementById('sel-211-1-ngoinha').value;
    const fb = document.getElementById('fb-ex1-211');
    fb.classList.remove('hidden');

    if (!giangiao || !betong || !ngoinha) {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-orange-100 text-orange-800 border border-orange-200 mt-4";
        fb.innerHTML = "⚠️ Em vui lòng chọn hình ảnh so sánh cho cả 3 chi tiết nhé!";
        return;
    }

    if (giangiao === 'tua_long' && betong === 'nhu_mam_cay' && ngoinha === 'bai_tho') {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-green-100 text-green-800 border border-green-200 mt-4";
        fb.innerHTML = "🌟 Xuất sắc! Em đã nối chính xác 100% các chi tiết miêu tả so sánh độc đáo trong bài thơ của tác giả!";
        if (window.UI && typeof window.UI.showToast === 'function') {
            window.UI.showToast("Rất tốt! Đáp án hoàn toàn chính xác.", "success");
        }
        if (typeof window.playAudioHelper === 'function') { window.playAudioHelper('correct'); }
        
        // Lưu điểm
        if (typeof window.submitMathLesson === 'function') {
            window.submitMathLesson("Đọc Tiết 211: Ghép nối chi tiết", 100, "ex-211-1", 1, 1, 1);
        }
    } else {
        fb.className = "p-4 rounded-xl font-bold text-lg bg-red-100 text-red-800 border border-red-200 mt-4";
        fb.innerHTML = "❌ Chưa chính xác rồi. Em hãy đọc kỹ lại khổ 1 và khổ 2 của bài thơ và chọn lại nhé!";
        if (window.UI && typeof window.UI.showToast === 'function') {
            window.UI.showToast("Chưa đúng, thử lại xem nhé!", "error");
        }
        if (typeof window.playAudioHelper === 'function') { window.playAudioHelper('incorrect'); }
    }
};

