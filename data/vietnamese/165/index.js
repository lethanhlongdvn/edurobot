// Chấm điểm bài điền từ bảo tàng
window.submitPractice165Hdt2 = function() {
    const w1 = document.getElementById("inp-165-hdt2-1")?.value.trim().toLowerCase() || "";
    const w2 = document.getElementById("inp-165-hdt2-2")?.value.trim().toLowerCase() || "";
    const w3 = document.getElementById("inp-165-hdt2-3")?.value.trim().toLowerCase() || "";
    const w4 = document.getElementById("inp-165-hdt2-4")?.value.trim().toLowerCase() || "";

    const fb = document.getElementById("fb-165-hdt2");

    if (!w1 || !w2 || !w3 || !w4) {
        fb.classList.remove("hidden", "bg-green-100", "text-green-800", "bg-red-100", "text-red-800");
        fb.classList.add("bg-amber-100", "text-amber-800");
        fb.innerHTML = "⚠️ Em hãy điền đầy đủ cả 4 ô trống trước khi nộp bài nhé!";
        return;
    }

    const isW1Correct = ["cổ thụ", "cothu"].includes(w1);
    const isW2Correct = ["cổ kính", "cokinh"].includes(w2);
    const isW3Correct = ["cổ đại", "codai"].includes(w3);
    const isW4Correct = ["cổ vật", "covat"].includes(w4);

    fb.classList.remove("hidden", "bg-amber-100", "text-amber-800");

    if (isW1Correct && isW2Correct && isW3Correct && isW4Correct) {
        fb.classList.remove("bg-red-100", "text-red-800");
        fb.classList.add("bg-green-100", "text-green-800");
        fb.innerHTML = "🎉 Tuyệt vời! Em đã điền chính xác tất cả các từ có tiếng 'cổ' thích hợp vào đoạn văn giới thiệu bảo tàng!";
    } else {
        fb.classList.remove("bg-green-100", "text-green-800");
        fb.classList.add("bg-red-100", "text-red-800");
        
        let errorMsg = "❌ Kết quả chưa chính xác:<br>";
        if (!isW1Correct) errorMsg += "• Ô (1): Nhắc đến cây lâu năm, ta dùng từ 'cổ thụ'.<br>";
        if (!isW2Correct) errorMsg += "• Ô (2): Nhắc đến toà nhà mang vẻ trang nghiêm xưa cũ, ta dùng từ 'cổ kính'.<br>";
        if (!isW3Correct) errorMsg += "• Ô (3): Nhắc đến thời kì lịch sử xa xưa, ta dùng từ 'cổ đại'.<br>";
        if (!isW4Correct) errorMsg += "• Ô (4): Nhắc đến hiện vật có giá trị từ xưa, ta dùng từ 'cổ vật'.<br>";
        errorMsg += "Em hãy sửa lại các lỗi trên và thử lại nhé!";
        fb.innerHTML = errorMsg;
    }
};

