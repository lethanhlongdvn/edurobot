window.checkMovieTicket = function() {
    const movie = document.getElementById('ticket-movie-name')?.value;
    const genre = document.getElementById('ticket-movie-genre')?.value;
    const time = document.getElementById('ticket-movie-time')?.value;
    const location = document.getElementById('ticket-movie-location')?.value;
    const feedback = document.getElementById('ticket-feedback');
    
    if (!feedback) return;
    feedback.classList.remove('hidden');

    if (!movie || !genre || !time || !location) {
        feedback.innerHTML = "⚠️ Em hãy điền đầy đủ các thông tin trên vé trước nhé!";
        feedback.className = "mt-6 p-4 rounded-xl font-bold text-lg bg-yellow-500 text-emerald-950 text-center animate-fade-in";
        return;
    }

    if (movie === "Chú Ốc Sên Bay" && 
        genre === "Phim hoạt hình" && 
        time === "Từ ngày 28.5.2022" && 
        location === "Trung tâm Chiếu phim Quốc gia") {
        
        feedback.innerHTML = "🎉 Tuyệt vời! Em đã xác định chính xác tất cả thông tin cốt lõi của tờ quảng cáo rồi đó!";
        feedback.className = "mt-6 p-4 rounded-xl font-bold text-lg bg-emerald-600 text-white text-center animate-fade-in shadow-lg";
        
        if (typeof window.UI?.showToast === 'function') {
            window.UI.showToast("Vé xem phim chính xác!", "success", 3000);
        }
    } else {
        feedback.innerHTML = "❌ Có thông tin chưa khớp với tờ quảng cáo. Em hãy quan sát kỹ tờ poster và chọn lại nhé!";
        feedback.className = "mt-6 p-4 rounded-xl font-bold text-lg bg-red-500 text-white text-center animate-fade-in shadow-lg";
        
        if (typeof window.UI?.showToast === 'function') {
            window.UI.showToast("Thông tin vé chưa chính xác!", "error", 4000);
        }
    }
};

