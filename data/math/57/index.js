// Chấm điểm Bài 1 (học sinh tải ảnh lên, giáo viên kiểm tra)
window.check_57_bt1 = async function() {
    var fileInput = document.getElementById('ans-57-1-upload');
    var file = fileInput && fileInput.files && fileInput.files[0];

    if (!file) {
        alert('⚠️ Em chưa tải ảnh bài vẽ lên! Hãy chụp ảnh bài làm và tải lên trước khi nộp bài nhé.');
        return;
    }

    var btn = document.getElementById('btn-check-57-bt1');
    if (btn) { btn.textContent = '⏳ Đang nộp...'; btn.disabled = true; }

    try {
        // Nén ảnh trước khi lưu
        var fileUrl = await new Promise(function(resolve, reject) {
            var reader = new FileReader();
            reader.readAsDataURL(file);
            reader.onload = function(e) {
                var img = new Image();
                img.src = e.target.result;
                img.onload = function() {
                    var canvas = document.createElement('canvas');
                    var MAX = 1000;
                    var w = img.width, h = img.height;
                    if (w > h) { if (w > MAX) { h = h * MAX / w; w = MAX; } }
                    else { if (h > MAX) { w = w * MAX / h; h = MAX; } }
                    canvas.width = w; canvas.height = h;
                    canvas.getContext('2d').drawImage(img, 0, 0, w, h);
                    resolve(canvas.toDataURL('image/jpeg', 0.75));
                };
                img.onerror = reject;
            };
            reader.onerror = reject;
        });

        var meta = window.MATH_BUILDER_METADATA.bai_tap[0];

        // Lưu điểm + ảnh lên Firestore
        if (window.submitMathLesson) {
            window.submitMathLesson(meta.title, 100, 'btn-check-57-bt1', 0, 1, 1, fileUrl);
        }

        // Thông báo nộp thành công
        if (window.showMathFeedback) {
            window.showMathFeedback(
                true,
                'Bài vẽ đã được nộp thành công.',
                '📷 Học sinh đã tải ảnh lên.',
                meta.guidance,
                meta.solution
            );
        }

    } catch(err) {
        console.error('Lỗi tải ảnh:', err);
        alert('❌ Có lỗi khi tải ảnh. Em hãy thử lại nhé!');
    } finally {
        if (btn) { btn.textContent = '✅ Đã Nộp Bài'; }
    }
};

