function setupEkeHandlers(eke) {
    var isDragging = false;
    var isRotating = false;
    var startX, startY;
    var ekeLeft = 350;
    var ekeTop = 150;
    var currentAngle = 0;
    
    var rotateHandle = eke.querySelector('#eke-rotate-handle');
    
    // Drag handler
    eke.addEventListener('mousedown', function(e) {
        if (e.target === rotateHandle || e.target.closest('button')) return;
        isDragging = true;
        startX = e.clientX - ekeLeft;
        startY = e.clientY - ekeTop;
        eke.style.cursor = 'grabbing';
        e.preventDefault();
    });
    
    // Rotate handler
    rotateHandle.addEventListener('mousedown', function(e) {
        isRotating = true;
        e.stopPropagation();
        e.preventDefault();
    });
    
    // Global mouse move & up
    document.addEventListener('mousemove', function(e) {
        if (isDragging) {
            ekeLeft = e.clientX - startX;
            ekeTop = e.clientY - startY;
            eke.style.left = ekeLeft + 'px';
            eke.style.top = ekeTop + 'px';
        } else if (isRotating) {
            var pivotX = ekeLeft + 20;
            var pivotY = ekeTop + 220;
            var dx = e.clientX - pivotX;
            var dy = e.clientY - pivotY;
            var angleRad = Math.atan2(dy, dx);
            currentAngle = (angleRad * 180 / Math.PI) + 90;
            eke.style.transform = `rotate(\${currentAngle}deg)`;
        }
    });
    
    document.addEventListener('mouseup', function() {
        isDragging = false;
        isRotating = false;
        eke.style.cursor = 'grab';
    });
    
    // Touch support
    eke.addEventListener('touchstart', function(e) {
        var touch = e.touches[0];
        if (e.target === rotateHandle || e.target.closest('button')) return;
        isDragging = true;
        startX = touch.clientX - ekeLeft;
        startY = touch.clientY - ekeTop;
    });
    
    rotateHandle.addEventListener('touchstart', function(e) {
        isRotating = true;
        e.stopPropagation();
    });
    
    document.addEventListener('touchmove', function(e) {
        if (e.touches.length === 0) return;
        var touch = e.touches[0];
        if (isDragging) {
            ekeLeft = touch.clientX - startX;
            ekeTop = touch.clientY - startY;
            eke.style.left = ekeLeft + 'px';
            eke.style.top = ekeTop + 'px';
            e.preventDefault();
        } else if (isRotating) {
            var pivotX = ekeLeft + 20;
            var pivotY = ekeTop + 220;
            var dx = touch.clientX - pivotX;
            var dy = touch.clientY - pivotY;
            var angleRad = Math.atan2(dy, dx);
            currentAngle = (angleRad * 180 / Math.PI) + 90;
            eke.style.transform = `rotate(\${currentAngle}deg)`;
            e.preventDefault();
        }
    }, { passive: false });
    
    document.addEventListener('touchend', function() {
        isDragging = false;
        isRotating = false;
    });
    
    // Export helper controls globally
    window.rotateEke = function(angleDelta) {
        currentAngle += angleDelta;
        eke.style.transform = `rotate(\${currentAngle}deg)`;
    };
    
    window.resetEke = function() {
        ekeLeft = 350;
        ekeTop = 150;
        currentAngle = 0;
        eke.style.left = ekeLeft + 'px';
        eke.style.top = ekeTop + 'px';
        eke.style.transform = `rotate(\${currentAngle}deg)`;
    };
}

// Hàm so sánh chữ không phân biệt hoa thường và khoảng trắng
function normalizeCompare(str1, str2) {
    if (!str1 || !str2) return false;
    return str1.replace(/\\s+/g, '').toLowerCase() === str2.replace(/\\s+/g, '').toLowerCase();
}

