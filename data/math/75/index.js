window._selectedFruit75 = null;
window._slots75 = { 1: '', 2: '', 3: '', 4: '' };

window.selectFruit75 = function(fruit) {
    const alreadyPlaced = Object.values(window._slots75).includes(fruit);
    if (alreadyPlaced) {
        return;
    }

    window._selectedFruit75 = fruit;

    const fruitMap = {
        'Nho': 'btn-fruit-Nho',
        'Cà chua': 'btn-fruit-Cachua',
        'Chuối': 'btn-fruit-Chuoi',
        'Dưa hấu': 'btn-fruit-Duahau'
    };

    Object.keys(fruitMap).forEach(f => {
        const btn = document.getElementById(fruitMap[f]);
        if (!btn) return;
        if (f === fruit) {
            btn.className = "px-4 py-2 bg-blue-600 text-white border-2 border-blue-600 rounded-xl font-bold transition-all cursor-pointer shadow-sm scale-105";
        } else {
            const isPlaced = Object.values(window._slots75).includes(f);
            if (isPlaced) {
                btn.className = "px-4 py-2 bg-slate-100 text-slate-400 border-2 border-slate-200 rounded-xl font-bold transition-all cursor-not-allowed opacity-50";
            } else {
                btn.className = "px-4 py-2 bg-white text-slate-700 border-2 border-slate-300 rounded-xl font-bold hover:bg-blue-50 hover:border-blue-500 transition-all cursor-pointer";
            }
        }
    });
};

window.clickSlot75 = function(slotNum) {
    const currentFruit = window._slots75[slotNum];

    if (currentFruit) {
        window._slots75[slotNum] = '';
        document.getElementById('slot-75-' + slotNum).innerText = '?';
        document.getElementById('slot-75-' + slotNum).className = "w-32 h-12 bg-white border-2 border-dashed border-slate-300 rounded-xl flex items-center justify-center font-black text-blue-700 cursor-pointer shadow-sm hover:border-blue-500 transition-all";
        
        document.getElementById('inp-75-bt3-' + (slotNum + 4)).value = '';

        window._selectedFruit75 = null;
        window.selectFruit75(null);
        return;
    }

    if (window._selectedFruit75) {
        const fruit = window._selectedFruit75;
        window._slots75[slotNum] = fruit;
        
        const slotEl = document.getElementById('slot-75-' + slotNum);
        slotEl.innerText = fruit;
        slotEl.className = "w-32 h-12 bg-blue-50 border-2 border-solid border-blue-500 rounded-xl flex items-center justify-center font-black text-blue-700 cursor-pointer shadow-sm transition-all";

        document.getElementById('inp-75-bt3-' + (slotNum + 4)).value = fruit;

        window._selectedFruit75 = null;
        window.selectFruit75(null);
    }
};

