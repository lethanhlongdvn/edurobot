window.submitDrawingToFirebase = async function(title, score, btnId, fileUrl) {
    const userRole = localStorage.getItem('userRole');
    const userApproved = localStorage.getItem('userApproved');

    if (!userRole || !userApproved) {
        alert("⚠️ Bạn cần đăng nhập tài khoản để lưu bài vẽ.");
        return;
    }

    const { name, cls, school } = window.getStudentInfo();
    if (!name || !cls || !school) {
        window.openStudentModal();
        return;
    }

    const btn = document.getElementById(btnId);
    const originalText = btn ? btn.innerHTML : "";
    if (btn) {
        btn.disabled = true;
        btn.innerHTML = '⏳ Gửi...';
    }

    try {
        const db = window.db || firebase.firestore();
        const lessonTitle = document.title.replace(" - EduRobot", "");
        const week = window.currentLessonData ? window.currentLessonData.week : "13";
        const period = window.currentLessonData ? window.currentLessonData.period : "61";
        
        const baseDocId = window.getSlug(name + '_' + cls + '_' + school + '_' + lessonTitle);
        const exMatch = title.match(/^(?:Hoạt động|Bài|)\s*(\d+)/i);
        const exId = exMatch ? "ex" + exMatch[1] : "general";

        const essayDocId = baseDocId + '_' + exId;

        // Lưu trực tiếp tệp ảnh vào fileUrl để Dashboard hiển thị
        await db.collection("essays_v2").doc(essayDocId).set({
            studentName: name,
            studentClass: cls,
            studentSchool: school,
            content: 'Học sinh đã hoàn thành bài vẽ: ' + title,
            fileUrl: fileUrl, // Ghi đè fileUrl bằng ảnh chụp hoặc canvas vẽ
            lessonTitle: lessonTitle,
            aiScore: parseInt(score) || 100,
            week: week,
            period: period,
            timeTaken: 0,
            deviceId: window.getDeviceId(),
            timestamp: firebase.firestore.FieldValue.serverTimestamp(),
            status: "Chưa chấm",
            subject: "Toán học",
            type: "math_lesson"
        });

        // Sync progress score
        const scoreKey = "scoreEx" + (exMatch ? exMatch[1] : "1");
        if (window.syncRealtimeProgress) {
            window.syncRealtimeProgress({ [scoreKey]: 100 });
        }

        if (typeof confetti === 'function') confetti();
    } catch(e) {
        console.error("Lỗi lưu bài vẽ:", e);
        alert("Có lỗi khi nộp bài: " + e.message);
    } finally {
        if (btn) {
            btn.disabled = false;
            btn.innerHTML = originalText;
        }
    }
};

