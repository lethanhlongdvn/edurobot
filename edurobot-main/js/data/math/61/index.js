window.setupCanvasDrawing = function(id) {
    const canvas = document.getElementById('canvas-' + id);
    if (!canvas) return;

    const ctx = canvas.getContext('2d');
    const rect = canvas.getBoundingClientRect();
    
    // Đặt kích thước thực cho canvas tương ứng client bounding
    canvas.width = rect.width;
    canvas.height = rect.height;

    // Cấu hình state ban đầu
    window.drawingStates[id] = {
        tool: 'pencil',
        color: '#3b82f6',
        width: 3,
        history: [],
        drawing: false,
        lastX: 0,
        lastY: 0,
        points: [],
        fileData: null
    };

    // Hàm vẽ lưới ô vuông phía sau làm nền
    const drawGridLines = () => {
        ctx.strokeStyle = '#f1f5f9';
        ctx.lineWidth = 1;
        const gridSize = 25; // 25px per grid square
        
        // Vẽ các cột dọc
        for (let x = 0; x < canvas.width; x += gridSize) {
            ctx.beginPath();
            ctx.moveTo(x, 0);
            ctx.lineTo(x, canvas.height);
            ctx.stroke();
        }
        // Vẽ các hàng ngang
        for (let y = 0; y < canvas.height; y += gridSize) {
            ctx.beginPath();
            ctx.moveTo(0, y);
            ctx.lineTo(canvas.width, y);
            ctx.stroke();
        }
    };

    // Vẽ lưới nền lần đầu
    drawGridLines();

    const getCoordinates = (e) => {
        const canvasRect = canvas.getBoundingClientRect();
        const clientX = e.touches ? e.touches[0].clientX : e.clientX;
        const clientY = e.touches ? e.touches[0].clientY : e.clientY;
        let x = clientX - canvasRect.left;
        let y = clientY - canvasRect.top;

        // Hút điểm lưới nếu dùng Line Tool (Ruler) để kẻ thẳng hàng
        if (window.drawingStates[id].tool === 'line') {
            const gridSize = 25;
            x = Math.round(x / gridSize) * gridSize;
            y = Math.round(y / gridSize) * gridSize;
        }
        return { x, y };
    };

    const startDraw = (e) => {
        e.preventDefault();
        const state = window.drawingStates[id];
        state.drawing = true;
        const { x, y } = getCoordinates(e);
        state.lastX = x;
        state.lastY = y;
        
        if (state.tool === 'line') {
            // Lưu lịch sử trước khi vẽ đường thẳng để xóa preview cũ
            state.points = [ {x, y} ];
            state.savedImage = ctx.getImageData(0, 0, canvas.width, canvas.height);
        }
    };

    const moveDraw = (e) => {
        if (!window.drawingStates[id].drawing) return;
        e.preventDefault();
        const state = window.drawingStates[id];
        const { x, y } = getCoordinates(e);

        if (state.tool === 'pencil') {
            ctx.beginPath();
            ctx.strokeStyle = state.color;
            ctx.lineWidth = state.width;
            ctx.lineCap = 'round';
            ctx.lineJoin = 'round';
            ctx.moveTo(state.lastX, state.lastY);
            ctx.lineTo(x, y);
            ctx.stroke();
            state.lastX = x;
            state.lastY = y;
        } else if (state.tool === 'line') {
            // Phục hồi lại canvas trước khi vẽ đường thẳng preview
            ctx.putImageData(state.savedImage, 0, 0);
            ctx.beginPath();
            ctx.strokeStyle = state.color;
            ctx.lineWidth = state.width;
            ctx.lineCap = 'round';
            ctx.moveTo(state.points[0].x, state.points[0].y);
            ctx.lineTo(x, y);
            ctx.stroke();
        }
    };

    const stopDraw = (e) => {
        const state = window.drawingStates[id];
        if (!state.drawing) return;
        state.drawing = false;

        // Lưu lịch sử để hoàn tác
        state.history.push(ctx.getImageData(0, 0, canvas.width, canvas.height));
    };

    // Đăng ký các sự kiện chuột & cảm ứng
    canvas.addEventListener('mousedown', startDraw);
    canvas.addEventListener('mousemove', moveDraw);
    canvas.addEventListener('mouseup', stopDraw);
    canvas.addEventListener('mouseleave', stopDraw);

    canvas.addEventListener('touchstart', startDraw, { passive: false });
    canvas.addEventListener('touchmove', moveDraw, { passive: false });
    canvas.addEventListener('touchend', stopDraw, { passive: false });
};

