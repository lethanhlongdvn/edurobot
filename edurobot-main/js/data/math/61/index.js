window.clearDraw = function(id) {
    const canvas = document.getElementById('canvas-' + id);
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    
    // Vẽ lại lưới ô vuông
    ctx.strokeStyle = '#f1f5f9';
    ctx.lineWidth = 1;
    const gridSize = 25;
    for (let x = 0; x < canvas.width; x += gridSize) {
        ctx.beginPath();
        ctx.moveTo(x, 0);
        ctx.lineTo(x, canvas.height);
        ctx.stroke();
    }
    for (let y = 0; y < canvas.height; y += gridSize) {
        ctx.beginPath();
        ctx.moveTo(0, y);
        ctx.lineTo(canvas.width, y);
        ctx.stroke();
    }

    const state = window.drawingStates[id];
    if (state) {
        state.history = [];
        state.fileData = null;
    }
};

window.undoDraw = function(id) {
    const state = window.drawingStates[id];
    if (!state || state.history.length === 0) return;
    
    const canvas = document.getElementById('canvas-' + id);
    if (!canvas) return;
    const ctx = canvas.getContext('2d');
    
    state.history.pop(); // Loại bỏ state hiện tại
    
    if (state.history.length === 0) {
        window.clearDraw(id);
    } else {
        ctx.putImageData(state.history[state.history.length - 1], 0, 0);
    }
};

window.handleCanvasFileUpload = function(id, input) {
    const file = input.files[0];
    if (!file) return;

    const reader = new FileReader();
    reader.readAsDataURL(file);
    reader.onload = function(e) {
        // Nén ảnh chất lượng để đảm bảo Firestore lưu trữ an toàn
        const img = new Image();
        img.src = e.target.result;
        img.onload = function() {
            const canvas = document.createElement('canvas');
            let width = img.width;
            let height = img.height;
            const MAX_SIZE = 800; // Limits dimension
            if (width > height) {
                if (width > MAX_SIZE) { height *= MAX_SIZE / width; width = MAX_SIZE; }
            } else {
                if (height > MAX_SIZE) { width *= MAX_SIZE / height; height = MAX_SIZE; }
            }
            canvas.width = width;
            canvas.height = height;
            const ctx = canvas.getContext('2d');
            ctx.drawImage(img, 0, 0, width, height);

            const compressedUrl = canvas.toDataURL('image/jpeg', 0.6);
            
            const state = window.drawingStates[id];
            if (state) {
                state.fileData = compressedUrl;
            }

            // Hiện preview
            const previewContainer = document.getElementById('preview-container-' + id);
            const previewImg = document.getElementById('preview-img-' + id);
            if (previewContainer && previewImg) {
                previewImg.src = compressedUrl;
                previewContainer.classList.remove('hidden');
            }
        };
    };
};

